#!/bin/sh
# Переносимая сверка вендор-копии кита с PIN — КАНОНИЧЕСКИЙ путь
# copy-integrity для потребителя ЛЮБОГО языка: CI потребителя исполняет
# этот скрипт, извлечённый из base (контракт бутстрапа ниже). Совет
# «Python-репо предпочтут существующий contract-тест» снят намеренно
# (седьмой заход гейта на #101): существующий механизм steward обнаруживает
# только contracts/*/v*/PIN и кита на scripts/review/PIN не видит — совет
# был fail-open; а свой pytest-тест в дереве PR страдает тем же
# bootstrap-провалом, что и сам чекер (PR правит тест+кит+PIN разом), и
# строго слабее извлечения из base. Только POSIX shell и стандартные
# утилиты, как весь кит.
#
# PIN — файл в формате sha256sum: `<64 hex>  <путь-от-корня>` по строке на
# файл; строки `#...` и пустые — комментарии (SOURCE-строка с SHA продюсера
# живёт там же). Проверяется ПЕРЕЧЕНЬ, не каталог: install-hook.sh и
# настроенная копия review-prompt.md — штатные соседи кита у потребителя, и
# «лишний файл» не должен спотыкать целостность (§5).
#
# Коды: 0 — копия совпадает; 1 — расхождение или отсутствие файла из
# перечня (все, не только первое: чинить по одному файлу за прогон — N
# прогонов вместо одного); 2 — ошибка конфигурации (нет PIN, битая строка,
# пустой перечень — нулевая проверка неотличима от пройденной и потому
# отказ, не успех).
#
# БУТСТРАП (@id:review-kit-checksum-bootstrap) — КОНТРАКТ ВЫЗЫВАЮЩЕГО, а не
# свойство этого скрипта: чекер доказуемо не может защитить сам себя — PR,
# правящий checksum.sh вместе с его строкой в PIN, глушит проверку, которую
# сам исполняет (major шестого захода гейта на #101). Поэтому CI
# потребителя ОБЯЗАН исполнять checksum.sh, ИЗВЛЕЧЁННЫЙ ИЗ BASE (тот же
# эшелон, что механика codex-review в workflow: инструменты — из base, код
# для проверки — из PR), а не из дерева PR. Остаточный случай —
# согласованная правка кит+PIN в ревью-PR — внутренне консистентен для
# любого офлайн-чекера и ловится второй гарантией: upstream-drift watch по
# расписанию (копия против дерева продюсера) плюс ревью ре-вендор-PR.
set -eu

usage() {
    echo "usage: checksum.sh --pin <file> [--root <dir>]" >&2
}

hash_file() {
    if command -v sha256sum >/dev/null 2>&1; then
        sha256sum "$1" | cut -d' ' -f1
    elif command -v shasum >/dev/null 2>&1; then
        shasum -a 256 "$1" | cut -d' ' -f1
    else
        echo "нет ни sha256sum, ни shasum — сверить копию нечем." >&2
        exit 2
    fi
}

# Обязательный ИНВЕНТАРЬ кита (§5 спеки) — ПОЛНЫЕ вендор-пути: PIN обязан
# покрыть каждый член — перечень существует, чтобы исключать известных
# не-китовых соседей (install-hook.sh, настроенный промпт), а не чтобы
# позволять пропуски: PIN без checksum.sh оставлял бы подменённый файл
# непроверенным при зелёном исходе (major гейта на #101, второй заход).
# Пути, не basename: обманки с правильными именами в чужих путях
# удовлетворяли бы инвентарь, пока настоящие вендор-пути дрейфуют (major
# третьего захода). Раскладка кита не свободна: local.sh вычисляет соседей
# от своего каталога, схему — от .github/codex; смена раскладки или состава
# — правка кита через ревью, синхронно со спекой.
#
# ПЕРЕХОДНЫЕ члены — `?path` (major восьмого захода): инвентарь зашит в
# чекер, а чекер исполняется из base — без переходного синтаксиса смена
# состава кита дедлочилась (ре-вендор с новым членом всегда красный у
# старого base-чекера) либо ломала все PR в окне между шагами. Двухшаговый
# ре-вендор состава: PR-1 — новый checksum.sh, где новый член указан как
# `?path` (для старого base-чекера это просто смена байтов члена); PR-2 —
# сам файл и его строка PIN. Между PR ничего не краснеет: optional-член без
# PIN-строки не требуется, с PIN-строкой — сверяется как обычный.
# Обязательным член становится следующим релизом кита. Удаление —
# зеркально: сперва член становится `?path`, затем файл и строка уходят.
#
# CHECKSUM_KIT_EXTRA только ДОБАВЛЯЕТ члены (обычные или `?переходные`) к
# зашитому обязательному инвентарю — хук тестов продюсера и переходных
# конфигураций вызывающего. Подмена инвентаря целиком (бывший
# CHECKSUM_KIT_INVENTORY) была рычагом fail-open: вызывающий сужал состав
# до одного файла и озеленял неполный кит (major десятого захода гейта на
# #101). Сужение невозможно по построению: обязательные члены зашиты
# всегда, env их не видит и не трогает.
required_kit_default="scripts/review/build-prompt.sh scripts/review/collect-context.sh scripts/review/apply-threshold.sh scripts/review/local.sh scripts/review/checksum.sh .github/codex/review-schema.json"
required_kit="$required_kit_default${CHECKSUM_KIT_EXTRA:+ $CHECKSUM_KIT_EXTRA}"

pin=""
root=""
while [ $# -gt 0 ]; do
    case "$1" in
        --pin)  [ $# -ge 2 ] || { usage; exit 2; }; pin="$2"; shift 2 ;;
        --root) [ $# -ge 2 ] || { usage; exit 2; }; root="$2"; shift 2 ;;
        *) usage; exit 2 ;;
    esac
done

[ -n "$pin" ] || { usage; exit 2; }
# PIN-симлинк — негодная конфигурация: якорь проверки обязан быть обычным
# файлом, как и члены кита (симметрия с проверкой компонентов ниже).
[ ! -L "$pin" ] || { echo "PIN — симлинк, а обязан быть обычным файлом: $pin" >&2; exit 2; }
[ -f "$pin" ] || { echo "нет файла PIN: $pin" >&2; exit 2; }
[ -r "$pin" ] || { echo "файл PIN нечитаем: $pin" >&2; exit 2; }
# Умолчание корня — от ПОЛОЖЕНИЯ PIN, не от cwd вызывающего: PIN канонически
# лежит в scripts/review/ (§5) — прогон из подкаталога или CI-шага с чужим
# working-directory не должен объявлять валидную копию дрейфующей (minor
# шестого захода гейта на #101; тот же класс, что умолчания local.sh от
# корня репо). Вывод — СТРОКОВЫМ срезом канонического хвоста, не
# `dirname/../..`: точки-точки резолвятся ядром СКВОЗЬ симлинк, и при
# подменённом каталоге scripts/review корень уезжал мимо репо — проверка
# краснела «6 файлов отсутствуют» вместо честного «СИМЛИНК в пути» (ложный
# диагноз; найдено собственным тестом симлинк-родителя на CI). PIN не на
# каноническом пути — не угадываем: --root задаётся явно.
if [ -z "$root" ]; then
    case "$pin" in
        */scripts/review/PIN)
            root=${pin%/scripts/review/PIN}
            [ -n "$root" ] || root="/" ;;
        scripts/review/PIN)
            root="." ;;
        *)
            echo "PIN не на каноническом пути scripts/review/PIN ($pin) —" \
                "задайте --root явно." >&2
            exit 2 ;;
    esac
fi
[ -d "$root" ] || { echo "нет каталога корня: $root" >&2; exit 2; }

checked=0
failed=0
seen_paths=""
# Построчный разбор без word-splitting пути: путь — всё после «хеш + два
# пробела», пробелы в нём легальны.
cr=$(printf '\r')
while IFS= read -r line || [ -n "$line" ]; do
    # Хвостовой \r срезается, как в collect-context.sh: чекаут с autocrlf
    # не должен краснить валидную копию (minor шестого захода).
    line=${line%"$cr"}
    case "$line" in
        ''|'#'*) continue ;;
    esac
    hash_expected=${line%%  *}
    path=${line#*  }
    # Битая строка — отказ, не пропуск: пропущенная строка это непроверенный
    # файл, который выглядел бы проверенным.
    case "$hash_expected" in
        *[!0-9a-f]*|'')
            echo "битая строка PIN (ожидался '<sha256>  <путь>'): $line" >&2
            exit 2 ;;
    esac
    if [ ${#hash_expected} -ne 64 ] || [ "$path" = "$line" ] || [ -z "$path" ]; then
        echo "битая строка PIN (ожидался '<sha256>  <путь>'): $line" >&2
        exit 2
    fi
    # Запись вне канонического инвентаря — негодный PIN (код 2), не дрейф:
    # настроенная копия review-prompt.md — данные репо вне copy-integrity
    # (§5), и PIN с такой записью превращал бы легальную настройку в «дрейф
    # кита, ре-вендорьте» (minor четвёртого захода гейта на #101). PIN —
    # ровно инвентарь, ни больше ни меньше.
    case " $required_kit " in
        *" $path "*|*" ?$path "*) ;;
        *)
            echo "PIN перечисляет файл вне состава кита (§5): $path —" \
                "copy-integrity его не покрывает, уберите строку." >&2
            exit 2 ;;
    esac
    checked=$((checked + 1))
    seen_paths="$seen_paths $path"
    # Симлинк в ЛЮБОМ компоненте пути — отказ ЦЕЛОСТНОСТИ, даже при
    # совпадающих байтах цели: `-f` разыменовывает, и структурно
    # подменённый кит проходил бы зелёным — как ссылкой на месте самого
    # файла (major четвёртого захода), так и заменой всего каталога
    # `scripts/review/` на ссылку (major пятого). Компоненты выше `$root`
    # не проверяются намеренно: `/tmp` на macOS — легальный симлинк, а
    # контракт раскладки начинается от корня репо. Тот же класс, что
    # «обычный файл, не симлинк» при извлечении механики из base в CI.
    symlinked=""
    prefix="$root"
    rest="$path"
    while [ -n "$rest" ]; do
        seg=${rest%%/*}
        if [ "$seg" = "$rest" ]; then rest=""; else rest=${rest#*/}; fi
        prefix="$prefix/$seg"
        if [ -L "$prefix" ]; then symlinked="$prefix"; break; fi
    done
    if [ -n "$symlinked" ]; then
        echo "СИМЛИНК в пути: $path (компонент $symlinked) — вендор-копия" \
            "обязана лежать обычными файлами в обычных каталогах." >&2
        failed=$((failed + 1))
        continue
    fi
    if [ ! -f "$root/$path" ]; then
        # Каталог/спецфайл на месте члена — не «отсутствует»: ложное «нет в
        # копии» отправляет чинить не то.
        if [ -e "$root/$path" ]; then
            echo "НЕ ОБЫЧНЫЙ ФАЙЛ: $path — на месте члена кита каталог или" \
                "спецфайл." >&2
        else
            echo "ФАЙЛ ОТСУТСТВУЕТ: $path (есть в PIN, нет в копии)" >&2
        fi
        failed=$((failed + 1))
        continue
    fi
    # Нечитаемый файл — отказ ЧЕКЕРА (код 2), не дрейф: байты сверить
    # невозможно, и «РАСХОЖДЕНИЕ, ре-вендорьте» было бы ложным диагнозом —
    # сломанный пайплайн хеширования давал пустой hash_actual (minor гейта
    # на #101).
    if [ ! -r "$root/$path" ]; then
        echo "файл из PIN нечитаем — сверить нечем (это не дрейф):" \
            "$path" >&2
        exit 2
    fi
    hash_actual=$(hash_file "$root/$path")
    # Пайплайн `sha256sum | cut` глотает статус хешера: файл, исчезнувший
    # или ставший нечитаемым МЕЖДУ пречеками и хешированием, давал пустой
    # hash_actual и «РАСХОЖДЕНИЕ, ре-вендорьте» — ложный диагноз (minor
    # седьмого захода). Не-хеш на выходе — отказ ЧЕКЕРА, не дрейф.
    case "$hash_actual" in
        *[!0-9a-f]*|'')
            echo "не удалось захешировать $path — отказ чекера, не дрейф" >&2
            exit 2 ;;
    esac
    if [ ${#hash_actual} -ne 64 ]; then
        echo "не удалось захешировать $path — отказ чекера, не дрейф" >&2
        exit 2
    fi
    if [ "$hash_actual" != "$hash_expected" ]; then
        echo "РАСХОЖДЕНИЕ: $path (PIN $hash_expected, копия $hash_actual)" >&2
        failed=$((failed + 1))
    fi
done < "$pin"

if [ "$checked" -eq 0 ]; then
    echo "PIN не перечисляет ни одного файла — нулевая проверка это отказ," \
        "не успех: $pin" >&2
    exit 2
fi

# Непокрытый член инвентаря — негодный PIN (код 2), не дрейф копии: файл
# может быть цел, но проверка о нём молчит.
# Пробельный кейс безопасен: канонические вендор-пути пробелов не содержат,
# а путь ИЗ PIN с пробелом просто не совпадёт с каноническим членом.
missing_kit=""
for member in $required_kit; do
    case "$member" in
        '?'*) continue ;;  # переходный член: отсутствие в PIN легально
    esac
    case " $seen_paths " in
        *" $member "*) ;;
        *) missing_kit="$missing_kit $member" ;;
    esac
done
if [ -n "$missing_kit" ]; then
    echo "PIN не покрывает состав кита (§5):$missing_kit — subset-PIN это" \
        "негодная конфигурация, не пройденная проверка." >&2
    exit 2
fi

if [ "$failed" -gt 0 ]; then
    echo "копия кита разошлась с PIN: $failed из $checked файла(ов)." \
        "Ре-вендор — см. runbook потребителя; это отказ целостности, не" \
        "дефект текущего PR." >&2
    exit 1
fi
echo "копия кита совпадает с PIN: $checked файла(ов)."
