#!/bin/sh
# Склейка инструкций ревьюера с дифом. Оба приходят ФАЙЛАМИ и склеиваются
# через `cat`: диф никогда не попадает ни в аргумент командной строки, ни в
# подстановку выражений — иначе его содержимое интерпретировалось бы как часть
# команды, а диф это недоверенный текст.
set -eu

usage() {
    echo "usage: build-prompt.sh --prompt <file> --diff <file>" \
        "[--context <file>] [--generated-list <file>]" \
        "[--max-diff-bytes N] [--max-diff-files N]" >&2
}

# Маркер конца зоны недоверенных данных обязан быть непредсказуем для самого
# дифа: литеральная строка (`@id:review-kit-diff-marker-hardening`, снято
# владельцем — гейт нашёл живой обход) позволяла патчу вставить собственный
# "конец дифа" и вывести хвост на верхний уровень промпта, откуда ревьюер
# читает инструкции как доверенные. Суффикс — первые 12 hex-символов sha256
# ОТ ВСЕГО СОДЕРЖИМОГО ДИФА, детерминированный (один и тот же вход — один и
# тот же суффикс, тесты воспроизводимы) и цикличный по построению: чтобы
# подделать закрывающий маркер, патч обязан заранее знать хеш своего
# собственного содержимого ПОСЛЕ вставки подделки — самоссылающийся поиск,
# для которого угадывание практически не работает.
hash_diff() {
    if command -v sha256sum >/dev/null 2>&1; then
        sha256sum "$1" | cut -c1-12
    elif command -v shasum >/dev/null 2>&1; then
        shasum -a 256 "$1" | cut -c1-12
    else
        echo "нет ни sha256sum, ни shasum — не могу построить маркер." >&2
        exit 2
    fi
}

prompt=""
diff=""
# Контекст необязателен: репозиторий без манифеста ревьюируется как прежде, по
# одному дифу. Обязательность живёт не здесь, а у вызывающего — он уже знает,
# настроен манифест или нет (код 3 от collect-context.sh).
context=""
# Потолки дифа. Один общий прогон на большом патче теряет и полноту, и
# точность, а молчаливая обрезка хуже обоих: «покрыл всё» читалось бы там, где
# модель видела половину. Потолок байтов — круглые 400 000 БАЙТ, не «400 КиБ»:
# обе цифры произвольны, но одна из них не требует пересчёта при чтении
# сообщения об отказе. Превышение — ЯВНЫЙ отказ (код 2) с называнием
# причины; chunked-режим — отдельный пункт плана
# (@id:review-kit-large-pr-mode), пока он не влит, честный отказ единственная
# правда. Проверка живёт ЗДЕСЬ, в общей точке склейки, а не в вызывающих:
# CI и local.sh иначе разошлись бы в лимитах молча.
max_diff_bytes=400000
max_diff_files=30
context_given=0
# Список generated-путей от ВЫЗЫВАЮЩЕГО (`--generated-list`), по одному пути
# на строку. Что считать generated, кит не решает и не угадывает: список
# строится из декларации самого репо — `.gitattributes linguist-generated`,
# прочитанной из дерева ревьюируемого коммита (`git check-attr --source`,
# см. local.sh). Семь заходов гейта на #99 показали, что любая эвристика
# (basename; манифест-сосед; курируемые каталоги; снапшот-каталоги) имеет
# конструируемый контрпример: fixtures-копия lock-файла, рукописный `.snap`,
# удаление манифеста вместе с lock'ом. Декларация контрпримеров не имеет по
# построению: объявление — решение репо и само проходит ревью через PR;
# не объявлено — ревьюируется построчно (отказ в сторону ревью). Атрибут —
# паттерн дерева, а не файл: удалённый lock-файл остаётся объявленным, пока
# `.gitattributes` ревьюируемого дерева его покрывает.
generated_list=""

while [ $# -gt 0 ]; do
    case "$1" in
        # Голый флаг без значения (нет $2) — ошибка конфигурации, а не молчаливый
        # сдвиг мимо края позиционных параметров: без сторожа `shift 2` на bash
        # молча съедает лишнее (exit 1), а на dash падает с сообщением самого
        # shell мимо usage() — платформозависимое поведение опаснее прямого exit 2.
        --prompt) [ $# -ge 2 ] || { usage; exit 2; }; prompt="$2"; shift 2 ;;
        --diff)   [ $# -ge 2 ] || { usage; exit 2; }; diff="$2"; shift 2 ;;
        --context)
            [ $# -ge 2 ] || { usage; exit 2; }
            context="$2"; context_given=1; shift 2 ;;
        --max-diff-bytes)
            [ $# -ge 2 ] || { usage; exit 2; }
            max_diff_bytes="$2"; shift 2 ;;
        --max-diff-files)
            [ $# -ge 2 ] || { usage; exit 2; }
            max_diff_files="$2"; shift 2 ;;
        --generated-list)
            [ $# -ge 2 ] || { usage; exit 2; }
            generated_list="$2"; shift 2 ;;
        *) usage; exit 2 ;;
    esac
done

# Несуществующий список — ошибка конфигурации, не молчаливый прогон с
# выключенным фильтром (fail-open прятал бы generated-фильтр целиком).
if [ -n "$generated_list" ]; then
    [ -f "$generated_list" ] || { echo "нет файла generated-списка: $generated_list" >&2; exit 2; }
    [ -r "$generated_list" ] || { echo "generated-список нечитаем: $generated_list" >&2; exit 2; }
fi

# Потолки обязаны быть целыми числами, и проверяется это ДО использования:
# нечисловой `--max-diff-bytes 1MiB` в `[ ... -gt ... ]` не падает громко, а
# делает условие ложным ВНУТРИ `if` — `set -e` там не действует, и свежий
# гардрейл молча выключается: fail-open защитного ограничения (находка первого
# прогона нового кита, #99). Невалидный лимит — конфигурационный отказ.
case "$max_diff_bytes" in
    ''|*[!0-9]*)
        echo "--max-diff-bytes обязан быть целым числом байт, получено: $max_diff_bytes" >&2
        exit 2 ;;
esac
case "$max_diff_files" in
    ''|*[!0-9]*)
        echo "--max-diff-files обязан быть целым числом, получено: $max_diff_files" >&2
        exit 2 ;;
esac

[ -n "$prompt" ] || { usage; exit 2; }
[ -n "$diff" ] || { usage; exit 2; }
[ -f "$prompt" ] || { echo "нет файла инструкций: $prompt" >&2; exit 2; }
[ -f "$diff" ] || { echo "нет файла дифа: $diff" >&2; exit 2; }
# `-f` проверяет существование, не читаемость: без прав на чтение `cat` ниже
# упал бы под `set -e` кодом 1 — а 1 через local.sh доезжает до хука как
# "найдены находки уровня blocker/major", и пуш заблокировался бы так, будто
# ревью нашло дефект в патче, хотя сломаны права на локальный файл.
[ -r "$prompt" ] || { echo "файл инструкций нечитаем: $prompt" >&2; exit 2; }
[ -r "$diff" ] || { echo "файл дифа нечитаем: $diff" >&2; exit 2; }
# Пустое значение `--context ""` — отказ, а не «флага не было»: вызывающий явно
# запросил контекст, и молча собрать diff-only промпт значило бы «неполный вход
# как успех». Отсутствие контекста выражается отсутствием флага, не пустотой.
if [ "$context_given" -eq 1 ]; then
    [ -n "$context" ] || { echo "--context передан с пустым значением" >&2; exit 2; }
    [ -f "$context" ] || { echo "нет файла контекста: $context" >&2; exit 2; }
    [ -r "$context" ] || { echo "файл контекста нечитаем: $context" >&2; exit 2; }
fi

# Generated/lock/snapshot-блоки ОПУСКАЮТСЯ из дифа до потолков — именованно,
# не молча: вместо тела блока остаётся строка-маркер с путём и размером, а
# промпт велит проверять такие файлы на согласованность с источником по
# дереву. Без этого перегенерированный uv.lock в одиночку пробивал бы байтовый
# потолок, и ревью отказывало на PR, который по правилу как раз ревьюируем
# (находка гейта на #99). Опущенные блоки не считаются и в потолок файлов —
# построчно они не ревьюируются.
#
# Опускается РОВНО объявленное — членство пути в `--generated-list`, никакой
# классификации внутри кита (довод у объявления generated_list выше).
# Кавыченные заголовки (`diff --git "a/..." ...` у путей со спецсимволами) с
# сырым путём списка не совпадают: их блок остаётся в дифе, и худший исход —
# явный отказ по потолку, не молчаливое опущение (fail в сторону ревью);
# нормализация кавыченной формы — отдельная правка кита
# (@id:review-kit-quoted-diff-headers).
# Фильтр включается ТОЛЬКО при непустом списке: awk на выходе нормализует
# хвостовой перевод строки, и прогон без generated-файлов получил бы другой
# маркер и не-побайтовый диф — свойство «без опций вывод неизменен»
# сломалось бы у всех ради ветки, нужной немногим. Пустой список — легитимное
# «в дифе нет объявленных», не ошибка.
if [ -n "$generated_list" ] && [ -s "$generated_list" ]; then
# trap уже может стоять у вызывающего окружения — свой файл прибираем сами.
filtered=$(mktemp)
awk -v gen_file="$generated_list" '
    BEGIN {
        while ((getline line < gen_file) > 0) gen[line] = 1
        close(gen_file)
    }
    /^diff --git / {
        # Блок generated, только если ОБЕ стороны заголовка объявлены:
        # классификация по одной b-стороне прятала rename рукописного файла
        # в объявленный путь (`a/notes.py b/uv.lock`) — удаление и перенос
        # кода уходили под слабое правило артефакта (четырнадцатый заход
        # гейта на #99). Для обычного блока стороны совпадают и правило
        # вырождается в прежнее членство.
        new_path = $NF; sub(/^b\//, "", new_path)
        old_path = $(NF-1); sub(/^a\//, "", old_path)
        generated = (new_path in gen) && (old_path in gen)
        if (generated) {
            printf "--- generated-файл опущен из дифа: %s — не ревьюируется построчно, проверяй согласованность с источником по дереву ---\n", new_path
            next
        }
    }
    generated { next }
    { print }
' "$diff" > "$filtered"
diff="$filtered"
fi

# Потолки меряют то, что ревьюируется ПОСТРОЧНО: маркеры опущения в замер
# байтов не входят — симметрично файловому потолку ниже. Иначе перегенерация
# тысяч снапшотов давала бы диф из одних маркеров шире потолка — отказ на
# PR, где всё построчное содержимое уже исключено (шестой заход гейта на
# #99). Маркер — одна строка на файл; промпт из многих тысяч маркеров
# принимается осознанно: это и есть тот PR, ради которого правило существует.
diff_bytes=$(grep -v '^--- generated-файл опущен из дифа: ' "$diff" \
    | wc -c | tr -d ' ')
# `grep -c` возвращает 1 на нуле совпадений — это не ошибка, а счётчик «0».
diff_files=$(grep -c '^diff --git ' "$diff" || true)
if [ "$diff_bytes" -gt "$max_diff_bytes" ] || [ "$diff_files" -gt "$max_diff_files" ]; then
    echo "диф больше поддерживаемого одним прогоном: $diff_files файл(ов)," \
        "$diff_bytes байт (потолки $max_diff_files / $max_diff_bytes)." >&2
    echo "Это отказ инструмента, не вердикт о патче: chunked-режим ещё не" \
        "реализован (@id:review-kit-large-pr-mode). Разбейте PR; в локальном" \
        "прогоне потолок поднимается явно (local.sh --max-diff-bytes/" \
        "--max-diff-files), в CI потолок меняется только правкой workflow" \
        "через ревью — runtime-ручки у гейта нет намеренно." >&2
    exit 2
fi

marker=$(hash_diff "$diff")

cat "$prompt"

# Контекст идёт ПЕРЕД дифом и в собственных маркерах. Он куда доверенней дифа —
# это содержимое base, прошедшее ревью, — но своя рамка нужна не ради недоверия,
# а чтобы граница между «как есть в целевой ветке» и «что предлагает патч»
# оставалась читаемой: без неё ревьюер не отличит текущий код от предложенного и
# начнёт находить дефекты в том, что уже смержено.
if [ -n "$context" ]; then
    ctx_marker=$(hash_diff "$context")
    printf '\n\n--- КОНТЕКСТ ИЗ BASE НАЧАЛО %s ---\n' "$ctx_marker"
    cat "$context"
    printf '\n--- КОНТЕКСТ ИЗ BASE КОНЕЦ %s ---\n' "$ctx_marker"
fi

printf '\n\n--- ДИФ НАЧАЛО %s ---\n' "$marker"
cat "$diff"
printf '\n--- ДИФ КОНЕЦ %s ---\n' "$marker"
rm -f "${filtered:-}"
