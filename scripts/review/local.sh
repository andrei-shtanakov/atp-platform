#!/bin/sh
# Локальный прогон ревью. НЕ производит governance evidence и ничего не
# публикует: его назначение — быстрый фильтр перед пушем, чтобы не жечь раунды
# CI. Авторитет остаётся у чека в CI.
#
# Здесь неизбежно используются промпт, схема и скрипты АВТОРА: локально base и
# head — одно рабочее дерево. В CI они читаются из base, чтобы автор патча не
# переписал инструкции своему ревьюеру; локально такого разделения нет и быть
# не может. Это цена, а не дефект — см. спеку §4.1.
#
# Коды выхода (конвенция репо, §7): 0 — чисто (в том числе «диф пуст» —
# определённое состояние, не «ревью прошло», модель не вызывается); 1 —
# предметный отказ (ревьюер нашёл проблему); 2 — ошибка конфигурации; 3 —
# механический сбой ревьюера.
#   5 — ревьюировать нечего: исходный диф непуст, но после фильтра области
#       не осталось ничего. НЕ то же, что 0 («пуст сам диапазон»): потребитель
#       обязан различать, иначе опубликует approve, которого не было.
set -eu

kit_dir="${REVIEW_KIT_DIR:-$(dirname "$0")}"
# Умолчания относительны корню репо, а не cwd: README велит запускать
# `sh scripts/review/local.sh`, и запускать будут откуда попало — из
# подкаталога relative-путь до промпта/схемы молча не резолвится. Вне
# git-репозитория `git rev-parse` сам падает кодом 128 — под `set -e` это
# утекло бы наружу как есть, вне объявленного §7 набора 0/1/2/3; страж
# переводит это в код кита с понятным сообщением.
if ! repo_root=$(git rev-parse --show-toplevel 2>/dev/null); then
    echo "прогон вне git-репозитория: не удалось определить корень" \
        "(git rev-parse --show-toplevel)." >&2
    exit 2
fi
schema="${REVIEW_SCHEMA:-$repo_root/.github/codex/review-schema.json}"
prompt="${REVIEW_PROMPT:-$repo_root/.github/codex/review-prompt.md}"
# --- харнесс ревьюера (спека 2026-09-14) ------------------------------------
# REVIEW_CMD — КОМАНДА, не путь к бинарю: умолчание несёт `exec` внутри
# себя, а не как отдельный литерал ниже в вызове. Раньше `exec` был жёстко
# приклеен к вызову, и REVIEW_CMD='codex exec --model X' искал файл с таким
# именем целиком (ENOENT → код 3 "ревьюер не отработал"). Подменить хочется
# команду целиком, включая флаги, — не только бинарь.
#
# Приоритет: НЕПУСТОЙ REVIEW_CMD — осознанный оверрайд целиком, резолв
# харнесса не запускается (D5); REVIEW_CMD="" — как unset, так работал
# `${REVIEW_CMD:-…}` и до патча, и обещание совместимости обязано это
# сохранить. Иначе — REVIEW_HARNESS (умолчание codex: строка `codex exec`
# в отпечатке НЕ меняется, опубликованные наследования остаются валидными —
# D1) и REVIEW_MODEL. Кит читает только окружение процесса: ни файлового,
# ни git-конфига (D2) — harness.env остаётся деталью review-pr.sh.
#
# REVIEW_MODEL="" и REVIEW_HARNESS="" — ОТКАЗЫ, не умолчания: пустое
# значение приходит только от явной, но сломанной настройки (`export
# REVIEW_MODEL=` без значения), и молча уйти на codex значило бы сжечь
# ровно тот лимит, ради которого переменная выставлялась. Факт объявления
# проверяется `${REVIEW_MODEL+x}`, а не `${REVIEW_MODEL:-…}` (D6).
# reviewer_exec — путь для АБСОЛЮТНОГО вызова ревьюера (находка терминального
# ревью этой ветки, см. run_reviewer() ниже); пусто — вызов идёт словами
# $review_cmd через word splitting, как и раньше. Инициализация здесь, а не
# только в ветке claude: под `set -u` переменная обязана существовать при
# любом исходе резолва (REVIEW_CMD-оверрайд её не выставляет вовсе).
reviewer_exec=""
# Sidecar-артефакты eval (спека review-eval §7): пути задаются окружением,
# пустое значение — отказ (прецедент REVIEW_MODEL), в отпечаток не входят.
if [ -n "${REVIEW_VERDICT_OUT+x}" ] && [ -z "$REVIEW_VERDICT_OUT" ]; then
    echo "REVIEW_VERDICT_OUT задан пустым — уберите переменную или назовите путь." >&2
    exit 2
fi
# Каталог вместо файла: без этой проверки `mv "$tmp" "$REVIEW_VERDICT_OUT"`
# переносит временный файл ВНУТРЬ каталога (POSIX-семантика mv), прогон
# завершается кодом 0 без вердикта по заявленному пути, а внутри каталога
# остаётся осиротевший `.verdict.*` — находка финального ревью этой ветки.
[ ! -d "${REVIEW_VERDICT_OUT:-}" ] || {
    echo "REVIEW_VERDICT_OUT: путь — каталог, а не файл: $REVIEW_VERDICT_OUT" >&2
    exit 2
}
# Наличие файла обязано означать результат ИМЕННО этого прогона (контракт
# eval: sidecar есть = ревьюер отработал) — прежний вердикт снимается до
# любой работы. Без этого сброса провал ревьюера (код 3, до копирующего
# блока ниже) оставлял бы файл предыдущего прогона на месте, и eval читал
# бы устаревший «успех» с чужими находками как результат текущего.
# Сам сброс — НЕ здесь: он выполняется после разбора аргументов, за ранними
# выходами режимов-запросов (steward#175, steward#176 — прислал arbiter).
# Инвариант «файл есть = результат ИМЕННО этого прогона» этого не требует:
# прогон, который по построению sidecar не производит (`--print-review-cmd`,
# `--fingerprint-only`, опечатка во флаге), и риска прочитать чужой файл не
# создаёт — он вообще ничего не обещает. Удалять чужой результат, ничего не
# произведя взамен, значит терять данные молча и с кодом 0. Проверки ФОРМЫ
# (пустое значение, каталог вместо файла) остаются здесь, в префлайте.
# REVIEW_USAGE_OUT содержательно пишет и заново инвалидирует при каждом своём
# запуске адаптер harness-claude, но местный прогон обязан отказывать на тех
# же условиях, что обещаны в README (пустое значение и каталог — код 2), а не
# молча уходить в codex-путь, где переменная вообще не проверяется.
if [ -n "${REVIEW_USAGE_OUT+x}" ] && [ -z "$REVIEW_USAGE_OUT" ]; then
    echo "REVIEW_USAGE_OUT задан пустым — уберите переменную или назовите путь." >&2
    exit 2
fi
[ ! -d "${REVIEW_USAGE_OUT:-}" ] || {
    echo "REVIEW_USAGE_OUT: путь — каталог, а не файл: $REVIEW_USAGE_OUT" >&2
    exit 2
}
# Инвалидация — ДО любой операции, способной завершить прогон раньше
# адаптера (потолок дифа build-prompt.sh, отказ манифеста контекста и т.п.):
# адаптер повторяет ту же инвалидацию для собственных прямых вызовов, но его
# инвалидация не срабатывает, если он вообще не запускается. Без этой
# страховки прежний usage.json пережил бы ранний отказ гардрейла, и eval
# приписал бы устаревшую стоимость сбою конфигурации, а не реальному прогону.
# Сброс перенесён за ранние выходы — см. комментарий у REVIEW_VERDICT_OUT.
# REVIEW_MODEL/REVIEW_EFFORT попадают в review_cmd ТЕКСТОМ, а run_reviewer()
# намеренно word-splits эту строку (REVIEW_CMD — команда целиком, включая
# флаги, — тот же контракт распространяется на собранную строку умолчания).
# Значит значение обязано быть ОДНИМ словом: `REVIEW_EFFORT='high --model
# claude-haiku'` иначе долетало бы до ревьюера лишним argv и подменяло бы
# модель мимо REVIEW_MODEL — находка финального ревью этой ветки (major).
# Безопасный алфавит — буквы, цифры и `. _ : / @ + -`: ни пробелов, ни
# кавычек, ни `$ ; & | \` и прочих метасимволов шелла.
check_safe_word() {
    # $1 — имя переменной (для сообщения), $2 — значение.
    case "$2" in
        *[!A-Za-z0-9._:/@+-]*)
            echo "$1: недопустимое значение (разрешены буквы, цифры и" \
                ". _ : / @ + -): $2" >&2
            exit 2
            ;;
    esac
}
if [ -n "${REVIEW_CMD:-}" ]; then
    review_cmd="$REVIEW_CMD"
else
    if [ -n "${REVIEW_MODEL+x}" ] && [ -z "$REVIEW_MODEL" ]; then
        echo "REVIEW_MODEL задан пустым — уберите переменную или назовите" \
            "модель." >&2
        exit 2
    fi
    if [ -n "${REVIEW_MODEL:-}" ]; then
        check_safe_word REVIEW_MODEL "$REVIEW_MODEL"
    fi
    # REVIEW_EFFORT — reasoning-уровень (спека review-eval D13): та же
    # пустота-отказ, что у REVIEW_MODEL, и теперь та же форма-проверка
    # (check_safe_word). Effort — часть команды, значит и отпечатка: при
    # REVIEW_CMD-оверрайде выше эта ветка не выполняется, и effort вместе с
    # harness/model игнорируется целиком.
    if [ -n "${REVIEW_EFFORT+x}" ] && [ -z "$REVIEW_EFFORT" ]; then
        echo "REVIEW_EFFORT задан пустым — уберите переменную или назовите" \
            "уровень." >&2
        exit 2
    fi
    if [ -n "${REVIEW_EFFORT:-}" ]; then
        check_safe_word REVIEW_EFFORT "$REVIEW_EFFORT"
    fi
    case "${REVIEW_HARNESS-codex}" in
        codex)
            review_cmd="codex exec${REVIEW_MODEL:+ -m $REVIEW_MODEL}${REVIEW_EFFORT:+ -c model_reasoning_effort=$REVIEW_EFFORT}"
            ;;
        claude)
            # Адаптер — член кита; зовётся по АБСОЛЮТНОМУ пути
            # `$kit_dir/harness-claude` (находка терминального ревью этой
            # ветки — префикс `PATH="$kit_dir:$PATH"` у вызова действовал бы
            # и для codex-умолчания, и посторонний `scripts/review/codex` у
            # потребителя — не член PIN, checksum лишние файлы игнорирует по
            # контракту — подменил бы ревьюера при зелёном copy-integrity;
            # PATH теперь не трогается вовсе, см. run_reviewer() ниже). В
            # отпечаток и --print-review-cmd идёт голое имя `harness-claude`,
            # а не абсолютный путь — иначе отпечатки разошлись бы между
            # машинами; строка машинно-независима и называет тот же файл
            # кита. Перекос версий копий кита — штатный режим раскатки: нет
            # адаптера — именованный отказ, не `command not found` → код 3.
            # checksum.sh сверяет байты, не режим, поэтому потерянный при
            # вендоринге бит исполнения ловится здесь.
            if [ ! -f "$kit_dir/harness-claude" ]; then
                echo "REVIEW_HARNESS=claude, а $kit_dir/harness-claude нет:" \
                    "кит обновлён наполовину — ре-вендорьте кит целиком" \
                    "или уберите переменную (умолчание codex)." >&2
                exit 2
            fi
            if [ ! -x "$kit_dir/harness-claude" ]; then
                echo "адаптер без бита исполнения:" \
                    "chmod +x $kit_dir/harness-claude" >&2
                exit 2
            fi
            reviewer_exec="$kit_dir/harness-claude"
            review_cmd="harness-claude --model ${REVIEW_MODEL:-claude-opus-5}${REVIEW_EFFORT:+ --effort $REVIEW_EFFORT}"
            ;;
        *)
            echo "неизвестный харнесс REVIEW_HARNESS='${REVIEW_HARNESS}'" \
                "(claude|codex)." >&2
            exit 2
            ;;
    esac
fi

base=""
# Граница доверия отдельно от диапазона дифа (steward#181 ← devtools#260).
# `--base` отвечал СРАЗУ на два разных вопроса: "что показать модели" и
# "откуда читать входы, которым кит доверяет" (декларация
# `linguist-generated`, курируемый контекст, repo-owned `review-scope.env`).
# Пока оба ответа совпадали, это было незаметно; адресный recheck — ревью
# только фикс-коммитов после красного вердикта — разводит их: сужающая база
# лежит НА ВЕТКЕ PR, и вместе с диапазоном внутрь PR уезжали бы доверенные
# входы. Автору достаточно объявить свой код generated коммитом до
# отревьюированной головы — узкий диф целиком состоит из "generated", модель
# не видит ни строки, кит выходит нулём, и обвязка публикует approve поверх
# доставленного request-changes. Довод кита "из merge-base читается только
# то, что уже прошло ревью" эту границу НЕ восстанавливает: тот круг
# кончился отказом, а "прошло ревью" здесь значит "влито в base".
#
# Умолчание — сегодняшнее поведение ровно: не задан `--trusted-base` —
# граница остаётся на `--base`, и ни одна git-команда ниже не меняется.
# Обратная совместимость тут не вежливость: кит вендорится в ~22 репо, и
# смена умолчания сдвинула бы отпечатки ревью у всех сразу.
trusted_base=""
trusted_base_explicit=0
# Факт «базу задали явно» нужен только выводу (см. блок границы доверия): на
# пути умолчания база — ветка по умолчанию, и говорить там не о чем.
base_explicit=0
head_ref="HEAD"
max_diff_bytes=""
max_diff_files=""
do_fetch=0
format="text"
# "origin" — умолчание, не жёсткая привязка: `git clone -o github` или
# переименованный remote раньше молча ломали угадывание ветки по умолчанию
# (жёстко зашитое "origin"), а при наличии и origin, и upstream (пуш реально
# идёт в upstream) диапазон считался бы от НЕ ТОГО remote'а — локальный
# зелёный относился бы к другому remote, чем тот, куда ветка реально уходит.
# Git передаёт имя remote хуку первым аргументом; --remote — явный канал для
# той же информации при прогоне без хука.
remote="origin"
remote_explicit=0
# Область ревью (спека среза B): оператор может разово вернуть прозу флагом
# --include-prose или REVIEW_INCLUDE_PROSE=1 (напр., ревью самого правила
# путей). Флаг сильнее переменной только в сторону включения — обе ветки
# устанавливают include_prose=1, отключить обратно флагом нельзя.
#
# REVIEW_INCLUDE_PROSE, не равный "1" (в т.ч. "0"/"no"/пустой), — ОТКАЗ, не
# "выключено": та же конвенция, что у REVIEW_MODEL/REVIEW_HARNESS выше —
# явная, но сломанная настройка не читается молча как её противоположность.
# `${REVIEW_INCLUDE_PROSE:+1}` раньше срабатывал на ЛЮБОМ непустом значении,
# и REVIEW_INCLUDE_PROSE=0 (оператор пытается ВЫКЛЮЧИТЬ фильтр) включал его
# (находка m-1 ревью этой ветки).
include_prose=0
if [ -n "${REVIEW_INCLUDE_PROSE+x}" ]; then
    case "$REVIEW_INCLUDE_PROSE" in
        1) include_prose=1 ;;
        *)
            echo "REVIEW_INCLUDE_PROSE='$REVIEW_INCLUDE_PROSE' — ожидается" \
                "'1' (--include-prose) или переменная не задана вовсе" \
                "(фильтр включён)." >&2
            exit 2
            ;;
    esac
fi
scope_rules="${REVIEW_SCOPE_RULES:-$kit_dir/prose-paths.env}"

usage() {
    echo "usage: local.sh [--base <ref>] [--trusted-base <ref>]" \
        "[--head <ref>] [--remote <name>]" \
        "[--fetch] [--format markdown|text]" \
        "[--max-diff-bytes N] [--max-diff-files N] [--fingerprint-only]" \
        "[--print-review-cmd] [--include-prose]" >&2
}

while [ $# -gt 0 ]; do
    case "$1" in
        # Голый флаг без значения (нет $2) — ошибка конфигурации, а не молчаливый
        # сдвиг мимо края позиционных параметров: без сторожа `shift 2` на bash
        # молча съедает лишнее (exit 1), а на dash падает с сообщением самого
        # shell мимо usage() — платформозависимое поведение опаснее прямого exit 2.
        # `base_explicit` ставится только на НЕПУСТОМ значении: пустое
        # `--base ""` ниже (`[ -z "$base" ]`) молча уезжает на ветку по
        # умолчанию, то есть прогон фактически идёт путём умолчания — и
        # советовать ему `--trusted-base` для «суженной базы» было бы
        # советом состоянию, которого нет (находка minor круга 3). Отказ
        # на пустом значении — как у `--trusted-base` ниже — был бы
        # честнее, но это СМЕНА семантики `--base` у ~22 потребителей,
        # и решать её внутри приёма двух чужих заявок нельзя:
        # @id:review-kit-empty-base-ruling.
        --base)
            [ $# -ge 2 ] || { usage; exit 2; }
            base="$2"
            [ -z "$base" ] || base_explicit=1
            shift 2 ;;
        # Пустое значение — отказ, а не "как будто не передавали": тот же
        # довод, что у --max-diff-bytes ниже. Молчаливый съезд на умолчание
        # вернул бы границу доверия внутрь PR именно у того вызывающего,
        # который её как раз и пытался вынести наружу.
        --trusted-base)
            [ $# -ge 2 ] || { usage; exit 2; }
            [ -n "$2" ] || { echo "--trusted-base передан с пустым значением" >&2; exit 2; }
            trusted_base="$2"; trusted_base_explicit=1; shift 2 ;;
        --head)   [ $# -ge 2 ] || { usage; exit 2; }; head_ref="$2"; shift 2 ;;
        --remote) [ $# -ge 2 ] || { usage; exit 2; }; remote="$2"; remote_explicit=1; shift 2 ;;
        --format) [ $# -ge 2 ] || { usage; exit 2; }; format="$2"; shift 2 ;;
        # Проброс потолков дифа в build-prompt.sh: гардрейл предлагает поднять
        # потолок явно, значит поддерживаемый вызывающий обязан уметь его
        # передать — иначе обещанный путь восстановления не существует
        # (находка гейта на #99). ЧИСЛОВАЯ валидация — в build-prompt.sh, но
        # пустое значение — отказ ЗДЕСЬ: проброс гейтится [ -n ], и явно
        # запрошенный оверрайд молча испарялся бы, а прогон шёл с умолчаниями
        # (minor тринадцатого захода; тот же довод, что у --context "").
        --max-diff-bytes)
            [ $# -ge 2 ] || { usage; exit 2; }
            [ -n "$2" ] || { echo "--max-diff-bytes передан с пустым значением" >&2; exit 2; }
            max_diff_bytes="$2"; shift 2 ;;
        --max-diff-files)
            [ $# -ge 2 ] || { usage; exit 2; }
            [ -n "$2" ] || { echo "--max-diff-files передан с пустым значением" >&2; exit 2; }
            max_diff_files="$2"; shift 2 ;;
        --fetch)  do_fetch=1; shift ;;
        # Отпечаток входа ревью (@id:review-dedup-diff-hash, steward#126):
        # пройти весь путь подготовки входа — резолв диапазона, диф, контекст,
        # generated-фильтр, потолки, сборку промпта — и вместо вызова ревьюера
        # напечатать в stdout ровно одну строку: 64-hex sha256 от framed-склейки
        # компонент входа. Режим обязан быть ОФФЛАЙН-вычислимым: одинаковый
        # вход должен давать одинаковый отпечаток независимо от доступности
        # remote, иначе наследование вердикта зависит от сети.
        # Печать эффективной команды ревьюера (D9): единственный источник
        # таблицы резолва — кит; review-pr.sh берёт отсюда reviewer_label.
        --print-review-cmd) print_cmd=1; shift ;;
        --fingerprint-only) fp_only=1; shift ;;
        --include-prose) include_prose=1; shift ;;
        *) usage; exit 2 ;;
    esac
done

if [ "${fp_only:-0}" -eq 1 ] && [ "$do_fetch" -eq 1 ]; then
    echo "--fingerprint-only несовместим с --fetch: отпечаток вычисляется" \
        "оффлайн, по локальному состоянию." >&2
    exit 2
fi
fp_only="${fp_only:-0}"

print_cmd="${print_cmd:-0}"
if [ "$print_cmd" -eq 1 ]; then
    if [ "$do_fetch" -eq 1 ] || [ "$fp_only" -eq 1 ]; then
        echo "--print-review-cmd несовместим с --fetch и --fingerprint-only:" \
            "он печатает команду и выходит, не трогая диапазон." >&2
        exit 2
    fi
    printf '%s\n' "$review_cmd"
    exit 0
fi

# Информационные строки прогона (диапазон, контекст, пустой диф) в fp-режиме
# уходят в stderr: контракт stdout для --fingerprint-only — ровно одна строка
# отпечатка при непустом успешно подготовленном входе и ничего при пустом дифе.
info() {
    if [ "$fp_only" -eq 1 ]; then echo "$@" >&2; else echo "$@"; fi
}

# --- Инвалидация sidecar-артефактов (после режимов-запросов) ----------------
# Инвариант контракта: «файл по REVIEW_VERDICT_OUT/REVIEW_USAGE_OUT есть =
# результат ИМЕННО этого прогона». Поэтому стираем прежний файл до всякой
# работы, а не после — устаревший вердикт не должен пережить ни пустой диф,
# ни пустой остаток после фильтра, ни падение ревьюера. Но стирать имеет
# право только прогон, который МОГ БЫ ревью провести: режимы-запросы
# (`--print-review-cmd` выше, `--fingerprint-only` ниже) ревьюера не зовут и
# вердикта не производят — снести чужой файл ради ответа на вопрос было бы
# чистой потерей данных. Валидация формы (пустое значение, каталог вместо
# файла) остаётся в префлайте и работает во всех режимах; сюда вынесен
# только `rm -f`.
#
# ГРАНИЦА, которую эта точка задаёт и которую нельзя переоценивать:
# конфигурационные отказы РЕЗОЛВА ХАРНЕССА (нет `harness-claude` на
# полуобновлённом ките, `REVIEW_MODEL=""`, небезопасное слово в
# `REVIEW_EFFORT`, кривой `REVIEW_INCLUDE_PROSE`) физически стоят выше — они
# обязаны отработать до `--print-review-cmd`, который печатает собранную
# строку, а значит и до разбора аргументов. На таком коде 2 прежний sidecar
# остаётся лежать. До переноса эти отказы его снимали; цена перекрыта тем,
# что иначе любой `--print-review-cmd` стирал результат прошлого прогона.
# Закрыть окно целиком можно только перестановкой резолва харнесса ниже
# разбора аргументов — отдельная правка (@id:review-kit-sidecar-reset-window).
# Штатный потребитель (`review_eval/runner.py`) на кит в этом не полагается
# и сам делает unlink перед прогоном. Находка приёмочного ревью PR #177.
if [ "$fp_only" -eq 0 ]; then
    [ -z "${REVIEW_VERDICT_OUT:-}" ] || rm -f "$REVIEW_VERDICT_OUT" || {
        echo "REVIEW_VERDICT_OUT: не удалить прежний файл $REVIEW_VERDICT_OUT" >&2
        exit 2
    }
    [ -z "${REVIEW_USAGE_OUT:-}" ] || rm -f "$REVIEW_USAGE_OUT" || {
        echo "REVIEW_USAGE_OUT: не удалить прежний файл $REVIEW_USAGE_OUT" >&2
        exit 2
    }
fi

# --- нужен ли remote вообще -------------------------------------------------
# Резолюция/угадывание remote'а имеет смысл только там, где remote РЕАЛЬНО
# нужен: вывести базу из умолчания (--base не задан) или работать с
# удалённым состоянием (--fetch, проверка свежести на remote-tracking
# базе). Полностью явная пара --base/--head, не ссылающаяся на
# remote-tracking namespace (например `--base HEAD~1 --head HEAD`), не
# трогает remote вовсе — `merge-base`, диф и ревьюер работают целиком
# локально. Раньше блок ниже отрабатывал БЕЗУСЛОВНО и валил репозиторий без
# единого remote'а отказом «нет ни одного remote», даже когда диапазон был
# задан полностью и удалённое состояние было не нужно.
#
# Полная форма (`refs/remotes/...`) однозначна без всякой проверки. Голое
# "есть `/`" — НЕТ: обычнейшее локальное имя ветки (`release/1.0`,
# `feature/x`, типовой git-flow нейминг) тоже содержит `/`, а remote к нему
# отношения не имеет. Раньше именно так и считалось (`*/*` → remote нужен),
# и заявленный интерфейс `--base <ref|sha>` ломался на самом обычном
# локальном имени: `--base release/1.0` в репозитории без remote'ов валился
# отказом «remote не настроен», хотя обе ссылки локальные.
#
# Шортхенд (`<remote>/<ветка>`, возможно ЕЩЁ не подтянутый локально —
# резолвить его здесь нельзя, см. round-12 находку 2) распознаём иначе:
# remote нужен, только если первый сегмент до `/` совпадает с именем РЕАЛЬНО
# существующего remote'а. Это та же самая проверка (`git remote get-url`),
# что уже используется чуть ниже для "origin" по умолчанию — не жёстче и не
# мягче: просто применена к литеральному первому сегменту `$base`, а не к
# фиксированному имени.
remote_needed=0
if [ -z "$base" ] || [ "$do_fetch" -eq 1 ]; then
    remote_needed=1
else
    case "$base" in
        refs/remotes/*) remote_needed=1 ;;
        */*)
            base_candidate="${base%%/*}"
            if git remote get-url "$base_candidate" >/dev/null 2>&1; then
                remote_needed=1
            fi
            ;;
    esac
fi

# --- remote по умолчанию: единственный не двусмыслен, но не догадка --------
# "origin" — умолчание, а не догадка сама по себе (см. комментарий выше). Но
# если пользователь НЕ указал --remote явно, а "origin" в принципе не
# существует как remote (не просто без настроенного HEAD — которое чинится
# сообщением ниже) и в репозитории ровно ОДИН remote, брать его — не
# эвристика: других кандидатов нет, это единственный непротиворечивый ответ.
# Раньше `git clone -o github` с единственным remote'ом и корректно
# настроенным `refs/remotes/github/HEAD` всё равно падал на буквальном
# "origin", хотя хук через --remote уже работает — документированный ручной
# `sh scripts/review/local.sh` был рассинхронизирован с тем же самым репо.
# Несколько remote'ов без "origin" среди них — угадывать какой из них
# нельзя (ровно то машинно-зависимое поведение, против которого написан
# §6), отказ с перечислением найденных.
if [ "$remote_needed" -eq 1 ] && [ "$remote_explicit" -eq 0 ] \
    && ! git remote get-url "$remote" >/dev/null 2>&1; then
    remote_list=$(git remote)
    remote_count=$(printf '%s\n' "$remote_list" | grep -c . || true)
    if [ "$remote_count" -eq 1 ]; then
        remote="$remote_list"
    else
        echo "remote '$remote' не настроен." >&2
        if [ "$remote_count" -eq 0 ]; then
            echo "В этом репозитории нет ни одного remote." >&2
        else
            echo "Найдены remote'ы:" >&2
            printf '%s\n' "$remote_list" | sed 's/^/  /' >&2
            echo "Несколько remote'ов, и среди них нет '$remote' —" \
                "угадывать нельзя. Укажите --remote <имя>." >&2
        fi
        exit 2
    fi
fi

# --- ветка по умолчанию: отказ, а не догадка -------------------------------
# Угадывание по списку завело бы машинно-зависимое поведение. Флот за такое уже
# платил: список зеркал Robin держал устаревшие имена репо и молча был слеп к
# двум активным.
if [ -z "$base" ]; then
    if ! ref=$(git symbolic-ref "refs/remotes/$remote/HEAD" 2>/dev/null); then
        echo "не задан refs/remotes/$remote/HEAD — ветку по умолчанию не угадываем." >&2
        echo "выполните: git remote set-head $remote -a   (или укажите --base)" >&2
        exit 2
    fi
    base="refs/remotes/$remote/${ref#refs/remotes/$remote/}"
fi

# --- ветка, отслеживаемая через remote-tracking ref -------------------------
# И путь умолчания, и явный --base могут указывать на `refs/remotes/$remote/*`
# — тогда имя ветки извлекается из base ОДНОЗНАЧНО, и запрошенные --fetch и
# проверка свежести исполнимы для нЕЁ точно так же, как на пути умолчания.
# Раньше явный --base безусловно читался как "не наша ветка по умолчанию" и
# --fetch на нём молча пропускался — даже когда база была ИМЕННО
# remote-tracking ref'ом того же remote и запрошенное было исполнимо
# (hotfix-ветка вида `--base refs/remotes/origin/release/1.0 --fetch`).
# Настоящая причина пропуска — база НЕ ЯВЛЯЕТСЯ remote-tracking ref'ом
# нужного remote (локальная ветка, голый SHA, ref другого remote'а), а не
# сам факт явного --base.
track_branch=""
if full_base=$(git rev-parse --symbolic-full-name "$base" 2>/dev/null); then
    # `--symbolic-full-name` разворачивает ЛЮБУЮ форму записи (`origin/master`,
    # `remotes/origin/master`, полную `refs/remotes/origin/master`) в
    # каноническую — надёжнее, чем сопоставлять текст по шаблону: шортхенд
    # `origin/master` (самая ходовая форма записи remote-tracking ref'а,
    # её пишут чаще полной) раньше НЕ распознавался textual-паттерном
    # `refs/remotes/$remote/*` и молча читался как "не remote-tracking",
    # хотя им был. Требует резолвящегося объекта — если base ещё не
    # подтянут локально, эта ветка не сработает, ниже есть fallback.
    case "$full_base" in
        "refs/remotes/$remote/"*)
            track_branch="${full_base#refs/remotes/$remote/}"
            base="$full_base"
            ;;
    esac
else
    # `--symbolic-full-name` требует, чтобы `$base` резолвился в существующий
    # объект — для ещё НЕ подтянутого локально remote-tracking ref'а (свежий
    # клон, `--base refs/remotes/$remote/<ветка>` — форма, которую README сам
    # и рекомендует) он не поможет. Полная текстовая форма при этом остаётся
    # распознаваемой БЕЗ резолва — то же сопоставление по шаблону, что и
    # раньше, как запасной путь.
    #
    # Шортхенд (`$remote/<ветка>`, например `origin/release/1.0`) — ТА ЖЕ
    # проблема ещё раз: он тоже не резолвится, пока не подтянут, и раньше
    # здесь не распознавался вовсе (fallback ловил только полную форму) —
    # `--base origin/release/1.0 --fetch` на свежем клоне печатал "--fetch
    # игнорируется" и падал на построении диапазона, хотя --fetch был
    # заведён ровно для этого случая. Резолва не требуется: если первый
    # сегмент буквально совпадает с именем remote'а, остаток — имя ветки;
    # `base` переписывается в полную форму, чтобы дальнейший код (--fetch,
    # `git rev-parse "$base"`) видел канонический ref, а не шортхенд.
    case "$base" in
        "refs/remotes/$remote/"*) track_branch="${base#refs/remotes/$remote/}" ;;
        "$remote/"*)
            track_branch="${base#"$remote"/}"
            base="refs/remotes/$base"
            ;;
    esac
fi

if [ "$do_fetch" -eq 1 ] && [ -z "$track_branch" ]; then
    echo "--fetch игнорируется: база не является remote-tracking ref'ом" \
        "$remote (локальная ветка, голый SHA или ref другого remote'а)." >&2
fi

# --- свежесть базы -----------------------------------------------------
# Устаревшая база молча сдвигает диапазон: локальный ревьюер смотрит на
# диф, которого в PR не будет. Показать обязаны; отказывать — нет, это
# инструмент скорости.
#
# Три разных исхода `ls-remote`, и они не взаимозаменимы: "не смогли
# проверить" (сети нет, `ls-remote` сам упал ненулевым кодом) и
# "определённо нет" (`ls-remote` отработал успешно кодом 0, но вернул
# пусто — ветки с этим именем на remote больше нет, например
# `refs/remotes/$remote/HEAD` не обновился после переименования ветки по
# умолчанию: сам он локальная ссылка и не обновляется собой) — РАЗНЫЕ
# состояния с разной причиной, и сваливать их в одно сообщение нельзя:
# второе — сигнал сильнее первого.
#
# ls-remote проверяется ЗДЕСЬ, ДО попытки --fetch, а не наоборот: иначе
# `git fetch` ветки, которой на remote уже нет, сам падает сырым кодом
# git, guard превращает это в "не удалось обновить" — и до диагностики,
# которая назвала бы настоящую причину (ветки нет, `set-head`), управление
# не доходит. Порядок — часть контракта: при переименованной ветке причина
# обязана быть настоящей что с `--fetch`, что без него.
# В fp-режиме сетевой проверки свежести нет вовсе (ls-remote — сеть): отпечаток
# считается по локальному состоянию, устаревшая база даст ЧЕСТНО другой
# отпечаток, чем у CI/свежего прогона, — промах кэша в сторону полного ревью.
if [ -n "$track_branch" ] && [ "$fp_only" -eq 0 ]; then
    ls_remote_ok=1
    if ! remote_line=$(git ls-remote --heads "$remote" "$track_branch" 2>/dev/null); then
        ls_remote_ok=0
    fi

    if [ "$ls_remote_ok" -eq 1 ] && [ -z "$remote_line" ]; then
        # Ветки на remote больше нет — тянуть нечего, и молчать об
        # истинной причине нельзя. --fetch здесь не помог бы, поэтому
        # попытка фетча ниже намеренно пропущена.
        echo "ВНИМАНИЕ: ветки '$track_branch' нет на $remote —" \
            "refs/remotes/$remote/$track_branch устарела (например, после" \
            "переименования или удаления этой ветки)." >&2
        echo "  диапазон посчитан против несуществующей на $remote ветки." >&2
        echo "  выполните: git remote set-head $remote -a" >&2
    elif [ "$do_fetch" -eq 1 ]; then
        # Отсутствие сети, протухшие credential'ы — `git fetch` сам падает
        # сырым кодом git (обычно 128) на команде, которую README же и
        # рекомендует. Под `set -e` это утекло бы наружу как есть, вне
        # объявленного §7 набора 0/1/2/3 — тот же класс, что уже правили
        # (repo-root, построение диапазона, схема/промпт). Сбой fetch —
        # ошибка конфигурации/окружения, код 2.
        if ! fetch_err=$(git fetch -q "$remote" "$track_branch" 2>&1); then
            echo "не удалось обновить $track_branch с $remote:" >&2
            echo "$fetch_err" >&2
            exit 2
        fi
    fi

    if [ "$ls_remote_ok" -eq 1 ] && [ -n "$remote_line" ]; then
        remote_sha=$(printf '%s' "$remote_line" | cut -f1)
        # Пересчитано ПОСЛЕ возможного --fetch выше: если он обновил
        # локальную ссылку, она уже совпадёт с remote_sha, и предупреждение
        # об устаревшей базе законно не напечатается. Но если --fetch НЕ
        # запрашивали, а ветка есть на remote (ls-remote выше это уже
        # подтвердил) и локально ЕЩЁ НЕ подтянута — `git rev-parse "$base"`
        # сам падает сырым кодом git (128), а не контрактным 2: свежий клон
        # плюс `--base refs/remotes/$remote/<ветка>` без --fetch — форма,
        # которую README сам и рекомендует.
        if ! local_sha=$(git rev-parse "$base" 2>/dev/null); then
            echo "ветка '$track_branch' есть на $remote, но локально ещё не" \
                "подтянута ($base не резолвится)." >&2
            echo "  выполните: git fetch $remote $track_branch" \
                "(или добавьте --fetch)." >&2
            exit 2
        fi
        if [ "$remote_sha" != "$local_sha" ]; then
            behind=$(git rev-list --count "$base..$remote_sha" 2>/dev/null || echo "?")
            echo "ВНИМАНИЕ: локальная база устарела." >&2
            echo "  локально:  $local_sha" >&2
            echo "  на $remote: $remote_sha  (отстаём на $behind коммит(ов))" >&2
            echo "  диапазон посчитан по устаревшей базе; --fetch обновит." >&2
        fi
    elif [ "$ls_remote_ok" -eq 0 ]; then
        echo "ВНИМАНИЕ: свежесть базы не проверена (нет связи с $remote)." >&2
    fi
fi

# --- диапазон --------------------------------------------------------------
# Обе команды могут упасть сырым кодом git (128 у rev-parse на неизвестной
# ссылке, 1 у merge-base без общего предка) — под `set -e` это утекло бы
# наружу как есть, а 1 в нашем контракте означает "есть находки уровня
# blocker/major": инвертированный сигнал, диапазон не построился, а хук
# скажет человеку, что ревью нашло проблемы. Оба вызова обёрнуты кодом 2.
if ! head_sha=$(git rev-parse "$head_ref" 2>/dev/null); then
    echo "не удалось разрешить --head $head_ref: неизвестная ссылка." >&2
    exit 2
fi
if ! mb=$(git merge-base "$base" "$head_sha" 2>/dev/null); then
    base_hint=$(git rev-parse --short "$base" 2>/dev/null || echo "$base")
    echo "не удалось построить диапазон между $base_hint и $head_sha:" \
        "нет общего предка либо база не разрешается." >&2
    exit 2
fi

# --- граница доверия ---------------------------------------------------
# Диапазон дифа посчитан выше и больше не участвует: здесь отвечают на
# ДРУГОЙ вопрос — из какой ревизии кит читает то, чему верит. Три таких
# входа, и все три ниже берутся отсюда, а не из `$mb`:
#   1. repo-owned `review-scope.env` (`git show "$trusted_mb:…"`);
#   2. курируемый контекст (`collect-context.sh --base "$trusted_mb"`);
#   3. декларация `linguist-generated` (`check-attr --source="$trusted_base"`
#      — с ВЕРХУШКИ, не из merge-base; довод у самого вызова ниже).
# Точки (merge-base для 1–2, верхушка для 3) сохранены как были: сдвиг
# границы меняет РЕВИЗИЮ, а не правило чтения.
#
# Отказы — код 2 с причиной: `--trusted-base` приходит от обвязки, и
# неразрешимая ссылка здесь означает сломанный вызов, а не "ревью нашло
# проблемы" (код 1) и не сбой ревьюера (код 3).
#
# Край, объявленный, а не закрытый: проверка свежести выше (ls-remote,
# --fetch) относится к `$base`. Устаревшая локально доверенная база даёт
# входы чуть старее, чем в CI, — как и устаревшая база диапазона даёт
# диапазон чуть другой. Тянуть её отдельно кит не станет: `--trusted-base`
# приходит от обвязки, которая уже знает, что и когда фетчила.
if [ "$trusted_base_explicit" -eq 0 ]; then
    trusted_base="$base"
    trusted_mb="$mb"
else
    if ! git rev-parse --verify --quiet "$trusted_base^{commit}" >/dev/null; then
        echo "не удалось разрешить --trusted-base $trusted_base:" \
            "неизвестная ссылка (для remote-tracking ref'а сперва" \
            "git fetch)." >&2
        exit 2
    fi
    if ! trusted_mb=$(git merge-base "$trusted_base" "$head_sha" 2>/dev/null); then
        echo "не удалось найти общего предка --trusted-base $trusted_base" \
            "и головы $head_sha: граница доверия не определена." >&2
        exit 2
    fi
fi

info "база:     $(git rev-parse --short "$base")"
info "голова:   $(git rev-parse --short "$head_sha")"
info "диапазон: ${mb}..${head_sha}"
# РАЗВЕДЁННЫЕ диапазон и граница оператор обязан видеть — иначе "почему этот
# файл показан целиком" не восстановить по выводу. Симметрично: молчаливое
# СОВПАДЕНИЕ границы с явно заданной базой — тоже факт, о котором стоит
# сказать, потому что именно он и есть эксплуатируемое состояние, когда
# обвязка сузила `--base`, а `--trusted-base` передать забыла (например,
# её вендор-копия отстала на релиз): кит в этот момент ЗНАЕТ, что граница
# читается с той же ревизии, но до этой строки молчал (находка minor
# приёмочного ревью этой ветки). Умолчание при этом не тронуто: отпечаток
# считается от prompt/schema/threshold/review_cmd и от вывода не зависит,
# так что наследования вердиктов у флота не сдвигаются.
#
# Условие — «базу задали ЯВНО», а не догадка о том, лежит ли она внутри PR.
# Отличить "сужение до ревизии ветки" от "база — ветка-цель" кит не может:
# у неразошедшейся ветки-цели `mb` тоже равен верхушке базы, и предупреждение
# по такому признаку кричало бы на штатном полном прогоне. Это ровно тот
# класс машинно-зависимых догадок, из-за которого отклонён `remote_ref`
# в `review-kit-explicit-target-base`. Строка поэтому не ставит диагноз, а
# называет то, что прогон СДЕЛАЛ; путь умолчания (хук, подавляющее
# большинство прогонов флота) молчит по-прежнему.
if [ "$trusted_base_explicit" -eq 1 ]; then
    info "доверенная база: $(git rev-parse --short "$trusted_base")" \
        "(входы ревью читаются отсюда, а не из диапазона)"
    # Свежесть проверяется только для `$base` (блок выше гейтится
    # `track_branch`). Для границы доверия это объявленный край, а не
    # упущение: чем и когда обновлялась доверенная ревизия, знает
    # вызывающий — он её и назвал. Молчать об этом нельзя: устаревшая
    # граница читает СТАРУЮ декларацию, а это направление отказа в
    # сторону сокрытия.
    #
    # Активная проверка (ls-remote по границе, как у базы) была написана и
    # ОТКАЧЕНА решением владельца 2026-09-21: заявки steward#181 она не
    # просила, а поверхность добавляла. Край остаётся объявленным.
    info "  свежесть доверенной базы кит не проверяет — она на вызывающем"
elif [ "$base_explicit" -eq 1 ]; then
    info "граница доверия совпадает с --base: декларация linguist-generated," \
        "курируемый контекст и review-scope.env читаются из этой же ревизии"
    info "  для адресного recheck по суженной базе передайте --trusted-base"
fi

work=$(mktemp -d)
# verdict_tmp объявлен здесь и ПУСТ, пока REVIEW_VERDICT_OUT не запрошен
# (заполняется ниже, в копирующем блоке) — единственная регистрация EXIT
# trap'а живёт тут же, а не переопределяется там, где verdict_tmp
# появляется. Тело trap'а — В ОДИНАРНЫХ кавычках: переменные разворачиваются
# в момент СРАБАТЫВАНИЯ, а не в момент регистрации. Прежняя форма
# (`trap "rm -rf '$work'; rm -f '$verdict_tmp'" EXIT`, интерполяция путей
# внутрь одинарных кавычек текстом) ломалась на апостроф в самом пути —
# закрывающая кавычка обрывалась раньше срока (находка гейта на этой ветке,
# `REVIEW_VERDICT_OUT` под каталогом вида `O'Connor/`).
verdict_tmp=""
trap 'rm -rf "$work"; [ -z "$verdict_tmp" ] || rm -f "$verdict_tmp"' EXIT

git diff "$mb..$head_sha" > "$work/diff.patch"
if [ ! -s "$work/diff.patch" ]; then
    # Отдельный штатный исход и в fp-режиме: отпечаток пустому входу не
    # выдумывается — stdout остаётся пустым, вызывающий читает «ревьюировать
    # нечего» как «наследовать нечего и ревьюировать нечего».
    info "ревьюировать нечего: диф пуст"
    exit 0
fi

# --- Область ревью: проза модели не показывается (спека среза B) ------------
# Фильтр стоит ПОСЛЕ проверки пустого дифа: «пуст диапазон» (0) и «пуст
# остаток после фильтра» (5) — разные факты, и обвязка обязана различать их,
# иначе прозаический PR получил бы approve, которого не выносила модель.
#
# Правило читается из ФАЙЛА КИТА, а он на авторитетном канале берётся из
# доверенного чекаута, не из дерева PR: PR не может расширить список того,
# что скрыто от его собственного ревьюера.
#
# Fail-closed в сторону ревью: нет файла, нечитаем, нет PROSE — фильтр не
# применяется, модель видит полный диф. Недоказанная проза не прячется.
#
# $1 — ключ (PROSE|CODE_OVERRIDE|PROSE_REVIEW|…), $2 — содержимое файла
# правила ПОСЛЕ обрезки пробелов по всей строке и удаления
# комментариев/пустых строк (см. вызов ниже), $3 — путь к файлу (для
# сообщений). Тот же контракт, что у read_scope_key в
# devtools/review-pr.sh:560-586 (референс среза A, спека §4.3): один ключ —
# одна непустая строка; ноль определений, больше одного, пустое значение —
# КАЖДОЕ из трёх делает ключ негодным. Разница с обвязкой принципиальна: там
# `die 2` (правило — конфигурация ВЫЗЫВАЮЩЕГО), здесь сама функция никогда
# не падает — при отказе пишет причину через `info()` и возвращает 1,
# `scope_key_value` остаётся пустым; что делать с отказом (fail-open в
# сторону ревью, как у PROSE/CODE_OVERRIDE ниже, или жёсткий `exit 2`, как у
# PROSE_REVIEW из review-scope.env) решает КАЖДЫЙ вызывающий сам — у двух
# потребителей этой функции в файле разная семантика "ключ не определён"
# (для PROSE/CODE_OVERRIDE это тоже отказ; для PROSE_REVIEW — штатный `off`),
# и оба различают её через `scope_key_status`, а не встроенным `exit`.
# Усечённая вендор-копия без CODE_OVERRIDE иначе молча расширила бы прозу
# на самый опасный класс путей (находка I-1 ревью этой ветки); тем же
# путём чинится `PROSE=` с пустым значением (находка m-2): пустая строка —
# тоже отказ, а не «PROSE есть, просто пуст».
#
# `scope_key_status` — второй выходной параметр, наравне со `scope_key_value`:
# "undefined" (ключ не встречен вовсе), "duplicate" (>1 раз), "empty"
# (единственное значение — пустая строка) или "ok" (успех). Заведён вместе с
# читателем `review-scope.env`, которому нужно отличить «ключа нет» (штатный
# `off`) от «ключ битый» (жёсткий отказ) — PROSE/CODE_OVERRIDE читают только
# факт неуспеха (return 1) и в статус не заглядывают, им все три причины
# равнозначны.
#
# $4 — необязательная фраза-следствие для случая "ключ не определён", по
# умолчанию "фильтр не применяется". Текст сообщения "undefined" ЗАДАЁТ
# ВЫЗЫВАЮЩИЙ, не функция: у PROSE/CODE_OVERRIDE "ключа нет" — отказ разбора,
# и "фильтр не применяется" там правда (умолчание и оставлено голым). У
# `review-scope.env` "ключа нет" — штатное состояние, при котором фильтр
# `prose-paths.env` как раз ПРОДОЛЖАЕТ применяться как обычно: то же голое
# умолчание там оказалось бы прямой ложью (I-2 финального ревью —
# воспроизведено: валидный `PROSE_REVIEW=off`, `docs/n.md` реально
# отфильтрован, а stdout утверждает обратное про "PROSE_REVIEW_PATHS").
#
# $5 — необязательная фраза-следствие для случая "ключ битый" (дубль или
# пустое значение), по умолчанию её нет вовсе. Отдельный параметр, а не $4:
# "ключа нет" и "ключ битый" ведут к РАЗНЫМ исходам у одного и того же
# вызывающего. У `review-scope.env` первое — штатный `off`, второе —
# немедленный `exit 2`; сообщение "фильтр не применяется", зашитое в эти две
# ветки прежде, было ложью по обеим осям: прогон не продолжается без
# фильтра, он прерывается (находка 2 из steward#176, прислал atp-platform).
# У PROSE/CODE_OVERRIDE оба исхода совпадают — там обе фразы одинаковы.
read_scope_key() {
    _rsk_key="$1"
    _rsk_matches=$(printf '%s\n' "$2" | grep "^${_rsk_key}=") || _rsk_matches=""
    _rsk_count=0
    [ -z "$_rsk_matches" ] \
        || _rsk_count=$(printf '%s\n' "$_rsk_matches" | wc -l | tr -d ' ')
    case "$_rsk_count" in
        0)
            info "правило области ревью ($3) не называет $_rsk_key —" \
                "${4:-фильтр не применяется}"
            scope_key_value=""
            scope_key_status="undefined"
            return 1
            ;;
        1) : ;;
        *)
            info "правило области ревью ($3): ключ $_rsk_key определён" \
                "$_rsk_count раз — файл битый; какое значение настоящее," \
                "решает человек, не разбор${5:+ — $5}"
            scope_key_value=""
            scope_key_status="duplicate"
            return 1
            ;;
    esac
    scope_key_value="${_rsk_matches#"${_rsk_key}="}"
    if [ -z "$scope_key_value" ]; then
        info "правило области ревью ($3): пустое значение $_rsk_key${5:+ — $5}"
        scope_key_status="empty"
        return 1
    fi
    scope_key_status="ok"
    return 0
}

# Repo-owned политика: репозиторий может ВЕРНУТЬ себе прозу, но не спрятать
# новое — расширение skip-набора живёт только в пиненом правиле. Читается из
# ДОВЕРЕННОЙ базы (`git show "$trusted_mb:путь"`), не из дерева: иначе PR
# отключал бы собственное ревью. При умолчании `$trusted_mb` == `$mb` —
# прежнее поведение буквально; с `--trusted-base` конфиг берётся с влитой
# базы, а не с ветки PR, куда его сузили диапазоном.
# Отсутствие файла — штатное умолчание `off`.
scope_cfg_path=".github/codex/review-scope.env"
prose_review=off
prose_review_paths=""
if [ "$include_prose" -eq 1 ]; then
    # --include-prose (флаг/окружение) уже решил вопрос на «полная
    # область» ДО чтения repo-owned конфига — конфиг способен только
    # РАСШИРИТЬ область (единственная ветка, трогающая include_prose,
    # это `PROSE_REVIEW=all` ниже), значит при уже принятом максимуме
    # разбирать его нечего. Раньше блок читался безусловно: чужой битый
    # review-scope.env ронял прогон кодом 2 ДО этой проверки, хотя
    # результат разбора всё равно был бы отброшен — для review-eval,
    # который всегда добавляет --include-prose, это значит "измеряемый
    # репозиторий с битым конфигом" превращалось в "прибор не измерил".
    :
elif scope_cfg=$(git show "$trusted_mb:$scope_cfg_path" 2>/dev/null); then
    # Тот же разбор, что у PROSE/CODE_OVERRIDE ниже по файлу (`read_scope_key`)
    # — не второй одноразовый sed/tr. Прежний `sed -n '…p' | tr -d
    # '[:space:]'` на дубле ключа склеивал ДВЕ строки в одну мусорную (без
    # разделителя — "offall"), которая тихо проваливалась в ветку
    # "неизвестное значение" ниже: отказ получался верным по коду, но
    # сообщение называло случайную склейку, а не настоящую причину (дубль
    # ключа). `read_scope_key` уже умеет отличать 0/1/>1 определений и
    # пустое значение по отдельности — переиспользуем его, а не гоним
    # третий вариант разбора того же формата в одном файле.
    #
    # Семантика здесь ДРУГАЯ, чем у fail-open PROSE/CODE_OVERRIDE: "ключа
    # нет вовсе" (scope_key_status=undefined) — штатный `off`, а не отказ
    # (репозиторий мог закоммитить файл ради одного PROSE_REVIEW_PATHS в
    # будущем и пока не назвать PROSE_REVIEW). "Дубль"/"пустое значение" —
    # НАСТОЯЩИЙ отказ конфигурации: неразобранный ключ нельзя молча читать
    # как `off` (тем более как `all`) — тот же довод, что у неизвестного
    # значения ниже, поэтому exit 2 на STDERR, а не info() на STDOUT.
    _scope_cfg_lines=$(printf '%s\n' "$scope_cfg" \
        | sed -e 's/^[[:space:]]*//' -e 's/[[:space:]]*$//' \
        | grep -v '^#' | grep -v '^$') || _scope_cfg_lines=""
    # $4 у PROSE_REVIEW переопределяет фразу-следствие для "ключ не
    # определён" (I-2 финального ревью): умолчание read_scope_key
    # ("фильтр не применяется") здесь было бы ложью — "ключа нет" для
    # `review-scope.env` означает штатный `off`, при котором фильтр
    # `prose-paths.env` как раз ПРОДОЛЖАЕТ применяться как обычно.
    if read_scope_key PROSE_REVIEW "$_scope_cfg_lines" "$scope_cfg_path" \
        "используется умолчание \`off\`" "прогон прерывается, см. отказ ниже"
    then
        prose_review="$scope_key_value"
    elif [ "$scope_key_status" != "undefined" ]; then
        echo "review-scope.env ($scope_cfg_path): PROSE_REVIEW не" \
            "разобран однозначно ($scope_key_status — дубль ключа или" \
            "пустое значение, см. причину выше) — неразобранный конфиг" \
            "нельзя читать в пользу МЕНЬШЕГО ревью." >&2
        exit 2
    fi
    case "$prose_review" in
        off|all) ;;
        paths)
            # `PROSE_REVIEW_PATHS` читается ТОЛЬКО здесь, внутри ветки
            # `paths` — не безусловно перед `case` (I-1 финального ревью,
            # воспроизведено: `PROSE_REVIEW=off` + забытая строка
            # `PROSE_REVIEW_PATHS=authored/*` в файле продолжала возвращать
            # эти пути под ревью, хотя `off`/README обещают полный фильтр
            # без исключений). Побочно чинит и m-4 того же ревью: дубль
            # `PROSE_REVIEW_PATHS` при `off`/`all`, где ключ не используется
            # вовсе, больше не отказывает — не о чем отказывать.
            #
            # Тот же приём, что у PROSE_REVIEW — не четвёртый одноразовый
            # sed/tr в этом файле. Дубль раньше молча склеивал ОБА списка
            # глобов через `tr '\n' ' '` (направление безопасное — больше
            # ревью, не меньше — но это последний ключ блока, разобранный
            # иначе троих соседей, а кит уезжает в 24 репо).
            #
            # "undefined"/"empty" здесь НЕ отдельное сообщение — обе
            # оставляют `prose_review_paths` пустым, и `[ -n ... ]` чуть
            # ниже даёт ЕДИНСТВЕННОЕ итоговое сообщение об ошибке; заводить
            # для них второе значило бы дублировать его же (проверено
            # руками: `PROSE_REVIEW_PATHS=` с пустым значением даёт ровно
            # одно сообщение "нечего возвращать ревьюеру", не два). $4 всё
            # равно задан — та стдаут-заметка от read_scope_key не должна
            # называть исход, который решает вызывающий, а не она.
            # "duplicate" — единственная НАСТОЯЩАЯ поломка ключа сама по
            # себе, отказ немедленно, тем же каналом (STDERR), что у
            # PROSE_REVIEW.
            if read_scope_key PROSE_REVIEW_PATHS "$_scope_cfg_lines" \
                "$scope_cfg_path" "см. отказ ниже" "прогон прерывается, см. отказ ниже"
            then
                prose_review_paths="$scope_key_value"
            elif [ "$scope_key_status" = "duplicate" ]; then
                echo "review-scope.env ($scope_cfg_path):" \
                    "PROSE_REVIEW_PATHS — дубль ключа (определён больше" \
                    "одного раза) — какое значение настоящее, решает" \
                    "человек, не разбор." >&2
                exit 2
            fi
            [ -n "$prose_review_paths" ] || {
                echo "PROSE_REVIEW=paths без PROSE_REVIEW_PATHS в" \
                    "$scope_cfg_path — нечего возвращать ревьюеру." >&2
                exit 2
            } ;;
        *)
            # Неизвестное значение — отказ, а не умолчание: неразобранный
            # конфиг означает «мы не знаем, что репо велел ревьюить», и
            # читать это в пользу МЕНЬШЕГО ревью нельзя.
            echo "неизвестное PROSE_REVIEW='$prose_review' в" \
                "$scope_cfg_path (ожидалось off|paths|all)." >&2
            exit 2 ;;
    esac
    [ "$prose_review" != "all" ] || include_prose=1
fi

prose_globs=""
code_globs=""
if [ "$include_prose" -eq 1 ]; then
    info "--include-prose: фильтр области ревью отключён на этом прогоне"
elif [ ! -f "$scope_rules" ] || [ ! -r "$scope_rules" ]; then
    # `-f`, не только `-r`: каталог с тем же именем читаем, но `grep`/`sed`
    # на нём падает внутри присваивания и валит скрипт кодом вне
    # объявленного набора (находка m-3 ревью этой ветки) — тот же приём,
    # что уже применён к $threshold_script в fp-блоке ниже.
    info "правило области ревью нечитаемо ($scope_rules) — фильтр не" \
        "применяется, ревьюер получает полный диф"
else
    # Комментарии и пустые строки — прочь ДО разбора ключей, пробелы
    # обрезаются по всей строке (контракт: "ведущие/хвостовые пробелы
    # обрезаются") — та же подготовка, что у read_scope_key обвязки.
    _scope_lines=$(sed -e 's/^[[:space:]]*//' -e 's/[[:space:]]*$//' \
        "$scope_rules" | grep -v '^#' | grep -v '^$') || _scope_lines=""
    if read_scope_key PROSE "$_scope_lines" "$scope_rules" \
        "фильтр не применяется" "фильтр не применяется"; then
        prose_globs="$scope_key_value"
        # CODE_OVERRIDE обязателен: отсутствие/дубль/пустота — тот же отказ,
        # что и у PROSE, и он гасит уже принятый PROSE — фильтр либо
        # применяется целиком по годному правилу, либо не применяется
        # вовсе, половины правила не бывает.
        if read_scope_key CODE_OVERRIDE "$_scope_lines" "$scope_rules" \
            "фильтр не применяется" "фильтр не применяется"; then
            code_globs="$scope_key_value"
        else
            prose_globs=""
        fi
    fi
fi

# 0 — путь проза, 1 — код. CODE_OVERRIDE сильнее PROSE. `set -f` обязателен:
# неквотированный глоб иначе развернулся бы по содержимому cwd вместо того,
# чтобы остаться шаблоном для `case`; снимается перед КАЖДЫМ возвратом.
path_is_prose() {
    set -f
    for _g in $prose_review_paths; do
        case "$1" in $_g) set +f; return 1 ;; esac
    done
    for _g in $code_globs; do
        case "$1" in $_g) set +f; return 1 ;; esac
    done
    for _g in $prose_globs; do
        case "$1" in $_g) set +f; return 0 ;; esac
    done
    set +f
    return 1
}

# Фильтр имеет право удерживать пути ТОЛЬКО если сборщик промпта умеет об
# этом удержании объявить. Перекос версий копий кита — объявленный штатный
# режим раскатки (новый `local.sh`, старый `build-prompt.sh`), и раньше он
# давал ровно тот дефект, ради которого написан steward#176, только тише:
# проза вырезалась из дифа, объявление до модели не доходило, чистый вердикт
# проходил порог кодом 0, и pre-push пропускал пуш. Предупреждения оператору
# для этого мало — оператора в прогоне хука нет.
#
# Направление отказа — то же, что у всякой другой негодности правила выше
# (нет файла, нечитаем, нет PROSE, дубль, пустое значение): фильтр
# выключается ЦЕЛИКОМ, модель получает полный диф. Ревью прозы дороже, чем
# нужно, но «дороже» и «тише, чем объявлено» — разные цены, и вторую кит не
# платит. Проверка стоит ДО фильтра, а не у передачи флага: там диф уже
# урезан, и восстановить его нечем.
if [ -n "$prose_globs" ] \
    && ! grep -q -- '--withheld-list' "$kit_dir/build-prompt.sh"; then
    info "build-prompt.sh этой копии кита не знает --withheld-list:" \
        "объявить удержанное нечем — фильтр области выключен целиком," \
        "ревьюер получает полный диф; ре-вендорьте кит"
    prose_globs=""
fi

if [ -n "$prose_globs" ]; then
    # `git diff --name-only` печатает пути ОТ КОРНЯ РЕПО; git-подстановка в
    # for-списке под `set -e` не проверяется автоматически (её код теряется в
    # $#-подсчёте цикла) — захватываем явно и проверяем статус, иначе сбой
    # git читался бы как «всё отфильтровано» вместо механического отказа
    # (находка m-3 ревью этой ветки).
    #
    # `-z`, не `-c core.quotePath=false --name-only`: quotePath спасает
    # только не-ASCII байты, а `"`, `\`, TAB и перевод строки git
    # C-квотирует ВСЕГДА, даже с quotePath=false (проверено: путь
    # `we"ird.py` приходит строкой `"we\"ird.py"`). Такая строка не
    # совпадает ни с одним глобом классификатора и не совпадает с
    # `:(top,literal)` реального файла — путь молча выпадал из дифа, диф
    # для целиком кодового диапазона с таким именем собирался бы ПУСТЫМ,
    # код 0, обвязка публикует approve на диапазоне, которого модель не
    # видела (C-1 финального ревью этой ветки — тот же инвариант §4.4, что
    # и у прежнего C-1 про подкаталог, другая дверь). `-z` отдаёт пути
    # сырыми байтами безусловно, quotePath на него не влияет вовсе.
    # NUL переводится в перевод строки СРАЗУ, при чтении временного файла,
    # а не после подстановки в переменную — тот же приём и тот же довод,
    # что уже применён в `collect-context.sh` (`git ls-tree -z | tr '\0'
    # '\n'`): bash 3.2 и dash не хранят NUL в значении переменной, и любой
    # `$(git diff -z ...)` тут же потерял бы все разделители. Расплата та
    # же, что там: перевод строки В САМОМ имени файла (не разделитель, а
    # часть пути) этим циклом по-прежнему не различается — редкий,
    # отдельный от C-1 случай, кит уже платит эту же цену в другом месте
    # того же файла.
    #
    # Статус git ловится ДО `tr`, отдельной командой в файл, не пайпом:
    # `if ! x=$(git ... | tr ...)` отразил бы код ВЫХОДА ПОСЛЕДНЕЙ команды
    # конвейера (`tr`, который читает пустой stdin и всегда успешен, даже
    # если `git diff` слева упал) — тот самый класс промаха, ради которого
    # этот страж вообще заведён, только теперь спрятанный внутри пайпа.
    # `pipefail` в POSIX sh недоступен (правило репо), значит статус можно
    # получить только раздельным вызовом.
    if ! git diff -z --no-renames --name-only "$mb..$head_sha" \
            > "$work/changed-paths.z"; then
        echo "не удалось перечислить изменённые пути для фильтра области" \
            "ревью (git diff --name-only, диапазон ${mb}..${head_sha})." >&2
        exit 3
    fi
    _changed_paths=$(tr '\0' '\n' < "$work/changed-paths.z")
    # Пути в позиционные параметры: список кодовых путей уходит в git с
    # магией `:(top,literal)`, НЕ голым `:(literal)`. `--name-only` печатает
    # пути от КОРНЯ репозитория, а pathspec резолвится от CWD — `:(literal)`
    # отключает только глоббинг, базу не меняет: прогон из подкаталога (кит
    # его прямо объявляет штатным, шапка выше) не совпадал ни с одним путём,
    # диф.patch собирался бы ПУСТЫМ для целиком кодового диапазона — молчание
    # читалось бы как «находок нет», код 0, обвязка публикует approve на
    # диапазоне, которого модель не видела (прежний Critical C-1 ревью этой
    # ветки). `:(top,...)` фиксирует базу в корне репо независимо от CWD.
    # --no-renames: и старый, и новый путь переименования проходят
    # классификацию.
    _old_ifs=$IFS
    IFS='
'
    set -f
    set --
    _prose_skipped=0
    : > "$work/withheld.list"
    for _f in $_changed_paths; do
        IFS=$_old_ifs
        set +f
        if path_is_prose "$_f"; then
            _prose_skipped=$((_prose_skipped + 1))
            printf '%s\n' "$_f" >> "$work/withheld.list"
        else
            set -- "$@" ":(top,literal)$_f"
        fi
        IFS='
'
        set -f
    done
    IFS=$_old_ifs
    set +f
    # Страж класса «перевод строки внутри имени файла» (блокер круга 2
    # приёмочного ревью этой ветки): `-z` выше отдаёт NUL-разделённые
    # записи, но `tr '\0' '\n'` в `_changed_paths` стирает разницу между
    # РАЗДЕЛИТЕЛЕМ записи и байтом перевода строки ВНУТРИ самого имени —
    # если имя файла содержит перевод строки, эта запись распадается в
    # цикле выше на два несуществующих пути (одна половина имени —
    # отдельная "запись"), и в pathspec/классификацию уходит мусор вместо
    # реального файла. Прежний страж (`! -s diff.patch` ниже) ловил только
    # вырожденную форму класса — когда разъехались ВСЕ пути диапазона;
    # рядом с любым обычным файлом он молчал, и повреждённый файл (с любым
    # содержимым, включая новый код) выпадал из-под ревью НИЖЕ прежнего
    # уровня покрытия — до фильтра области он доходил до ревьюера целиком
    # (полный `git diff` без pathspec, код чуть выше).
    #
    # Источник истины о числе РЕАЛЬНЫХ записей — число NUL-байтов в сыром
    # `changed-paths.z`: `-z` терминирует НУЛЁМ каждую запись, включая
    # последнюю (не разделяет между ними) — значит NUL-байтов ровно
    # столько же, сколько путей отдал git. Сравниваем это число со
    # счётчиком путей, фактически разобранных циклом (код ушёл в
    # позиционные параметры — `$#`, проза — в `_prose_skipped`; сумма
    # обязана совпасть). Расхождение возможно только если запись
    # распалась на два псевдо-пути — отказ кодом 3 (механический сбой
    # инструмента), а не тихое продолжение на мусорных путях.
    _nul_count=$(tr -cd '\0' < "$work/changed-paths.z" | wc -c | tr -d ' ')
    _parsed_count=$(($# + _prose_skipped))
    if [ "$_nul_count" -ne "$_parsed_count" ]; then
        echo "фильтр области ревью: разбор изменённых путей разъехался с" \
            "исходным списком git (NUL-записей: $_nul_count, разобрано:" \
            "$_parsed_count) — вероятная причина: перевод строки внутри" \
            "имени файла ломает разделитель записей после подмены" \
            "NUL→\\n; такие имена этот кит не поддерживает (диапазон" \
            "${mb}..${head_sha})." >&2
        exit 3
    fi
    if [ "$#" -eq 0 ]; then
        info "ревьюировать нечего: всё отфильтровано как проза" \
            "(правило $scope_rules)"
        exit 5
    fi
    # Частичное усечение обязано быть объявлено (steward#176, прислал
    # atp-platform): прежде счётчик рос молча, и прогон со снятой прозой
    # выглядел полным. Довод — тот же, что у полного усечения (exit 5) выше:
    # потребитель обязан различать, иначе опубликует вердикт, которого не
    # было. Здесь цена мягче — не ложный approve, а ложное «патч не трогает
    # документацию» в тексте модели, — но природа та же: артефакт утверждает
    # больше, чем показано. Оператору — сюда, модели — маркером в промпте
    # (`--withheld-list` ниже).
    if [ "$_prose_skipped" -gt 0 ]; then
        info "фильтр области: удержано $_prose_skipped путь(ей) как проза," \
            "ревьюируется остаток (правило $scope_rules)"
    fi
    # m-1 финального ревью: пересборка дифа была не защищена вовсе, хотя
    # соседний `--name-only` чуть выше обёрнут именно с доводом «сбой git не
    # должен читаться как результат» — здесь сбой (128) под `set -e` утёк бы
    # кодом вне объявленного набора 0/1/2/3/5.
    if ! git diff "$mb..$head_sha" -- "$@" > "$work/diff.patch"; then
        echo "не удалось собрать диф после фильтра области ревью" \
            "(git diff -- <pathspec>, диапазон ${mb}..${head_sha})." >&2
        exit 3
    fi
    # Fail-closed страж (C-1 финального ревью, вторая обязательная половина
    # правки): выше уже проверено `$# -gt 0` — классификация нашла хотя бы
    # один НЕ-прозаический путь (иначе уже был бы `exit 5`). Значит непустой
    # `diff.patch` здесь ГАРАНТИРОВАН, если классификация и pathspec
    # согласованы. Пустой результат — не «находок нет», а сломанный
    # инструмент: pathspec не совпал ни с одним реальным путём (например,
    # квотирование спецсимвола — уже найденная форма). Класс «перевод
    # строки внутри имени файла» этот страж НЕ ловит (одна прозаическая
    # половина разъехавшейся записи гасит совпадение молча, диф собирается
    # непустым) — для него отдельный, более ранний страж по счётчику NUL
    # выше (блокер круга 2 этой ветки); здесь — оставшийся периметр:
    # рассогласования pathspec/дифа, не сводящиеся к порче самого списка
    # путей.
    if [ ! -s "$work/diff.patch" ]; then
        echo "фильтр области ревью оставил $# путь(ей) кодом, но диф" \
            "после пересборки пуст — pathspec не совпал ни с одним" \
            "реальным путём (git diff -- <pathspec>, диапазон" \
            "${mb}..${head_sha})." >&2
        exit 3
    fi
fi

# Схема и промпт — вход ревьюера. Отсутствие любого из них — конфигурационный
# отказ (код 2), не механический сбой самого ревьюера (код 3): без этого
# preflight'а отсутствующая схема доходила бы до `codex exec --output-schema
# <нет-файла>`, падала бы уже там, и ветка "ревьюер не отработал" маскировала
# бы сломанную локальную конфигурацию под сбой инструмента — тот же класс, что
# правили уже дважды (repo-root, построение диапазона). Промпт проверен здесь
# же ради симметрии сообщения — `build-prompt.sh` ниже и сам его проверяет, но
# заставлять вызывающего искать причину в чужом скрипте, когда отказ
# произошёл здесь, не лучше.
[ -f "$schema" ] || { echo "нет файла схемы: $schema" >&2; exit 2; }
[ -f "$prompt" ] || { echo "нет файла инструкций: $prompt" >&2; exit 2; }
# `-f` проверяет существование, не читаемость — тот же класс, что уже
# закрыт в build-prompt.sh для промпта и дифа (находка 21), но остался
# незакрытым здесь для схемы: нечитаемая (`chmod 000`) схема раньше
# доходила до `codex exec`, тот отказывал, и "ревьюер не отработал" (код
# 3) выдавался вместо честного конфигурационного отказа (код 2). Промпт
# симметрично проверен и здесь, хотя `build-prompt.sh` его уже проверяет —
# по той же причине, что и `-f` выше.
[ -r "$schema" ] || { echo "файл схемы нечитаем: $schema" >&2; exit 2; }
[ -r "$prompt" ] || { echo "файл инструкций нечитаем: $prompt" >&2; exit 2; }

# Курируемый контекст. Локально промпт и схема неизбежно берутся из рабочего
# дерева автора (см. шапку); для контекста это верно наполовину — СПИСОК и
# СОДЕРЖИМОЕ читаются через `git show <доверенная база>:<путь>`, то есть из
# той же точки, что и в CI, а вот сам сборщик берётся из кита автора, как и
# остальное. Доверенная база — `$trusted_mb`, а НЕ `$mb`: контекст подаётся
# модели как авторитетные контракты и инварианты, и сузившийся диапазон не
# вправе переселить его внутрь ревьюируемого PR (steward#181).
#
# Манифест, в отличие от схемы и промпта выше, — НЕ путь в файловой системе,
# а путь в дереве доверенной базы от корня репозитория: он читается
# `git show`/`ls-tree`, и к `$repo_root` его приклеивать нельзя. От cwd он не зависит —
# `collect-context.sh` резолвит его `--full-tree` (steward#150); абсолютный
# путь или `..` в переопределении сборщик отвергает кодом 2.
manifest="${REVIEW_CONTEXT_MANIFEST:-.github/codex/review-context.txt}"
use_context=0

# Сборщика может не быть рядом: кит обновили наполовину, или потребитель ещё не
# скопировал файл. CI такой случай различает явно, и локальный прогон обязан
# вести себя так же — расходящиеся половины одного кита расходятся дальше.
# Без этой ветки `sh <нет файла>` дал бы `can't open`, и весь прогон падал бы
# кодом 2 там, где по документации должно быть штатное «контекст не настроен».
#
# Молчать можно только когда нет ОБОИХ: манифест в базе без сборщика — не
# бутстрап, а поломка (механику потеряли, данные остались), и она должна быть
# отказом, а не тихим съездом на «только диф».
if [ -f "$kit_dir/collect-context.sh" ]; then
    set +e
    sh "$kit_dir/collect-context.sh" --base "$trusted_mb" --manifest "$manifest" \
        > "$work/context.txt" 2> "$work/context.err"
    ctx_code=$?
    set -e
    case "$ctx_code" in
        0)
            use_context=1
            info "контекст: $(grep -c "^--- ФАЙЛ " "$work/context.txt") файл(ов)" \
                "из $(git rev-parse --short "$trusted_mb")"
            ;;
        3)
            info "контекст: не настроен ($manifest нет в базе) — ревью по одному дифу"
            ;;
        *)
            # Формулировка НЕЙТРАЛЬНА к причине: сюда приходит и «манифест
            # есть, но сломан», и отказ по форме пути `--manifest`, который
            # сборщик выносит ДО проверки наличия в base — утверждать
            # «манифест есть» здесь значило бы заявлять непроверенное.
            # Причина уже напечатана сборщиком строкой выше.
            cat "$work/context.err" >&2
            echo "сборщик контекста отказал (код $ctx_code) —" \
                "ревью без контекста не выдаётся за ревью с ним." >&2
            exit 2
            ;;
    esac
elif git cat-file -e "$trusted_mb:$manifest" 2>/dev/null; then
    echo "манифест контекста есть в базе, а $kit_dir/collect-context.sh нет:" \
        "механика потеряна, данные остались." >&2
    exit 2
else
    info "контекст: сборщика нет в ките — ревью по одному дифу"
fi

# Ветвление, а не сборка аргументов в строку: `ctx_args="--context $work/..."` с
# последующим некавыченным раскрытием разваливается, как только в `TMPDIR` есть
# пробел (`/tmp/Review Temp.XYZ`) — argv битый, и прогон падает на «нет файла
# контекста». Прежний комментарий утверждал «либо пуст, либо ровно два слова»;
# это было неверно, и неверно ровно там, где путь приходит извне.
# Позиционные параметры шелла — единственный способ собрать argv по частям
# без некавыченного раскрытия строки (тот же урок, что с ctx_args): `set --`
# строит список, кавычки сохраняют каждый элемент целым.
# Generated — то, что репо ОБЪЯВИЛ: `.gitattributes linguist-generated`,
# прочитанный из ВЛИТОЙ базы (`check-attr --source=$trusted_base`), не из
# head и не из checkout. Источник — граница доверия (девятый заход гейта на
# #99): декларация из самого патча прятала бы произвольный рукописный код —
# автору достаточно объявить файл generated тем же коммитом; из влитой базы
# же читается только то, что уже прошло ревью (CI симметрично читает из
# base PR). Именно `$trusted_base`, а не `$base`: при сужении диапазона до
# прошлой отревьюированной головы `$base` лежит ВНУТРИ PR, и декларация,
# добавленная коммитом ветки, снова стала бы действующей в собственном же
# ревью — та самая дыра адресного recheck (steward#181).
# Свежая декларация не действует в собственном PR: файл остаётся
# в дифе (отказ в сторону ревью) и фильтруется со следующего PR. Атрибут —
# паттерн дерева, не файл: удалённый lock-файл остаётся объявленным, пока
# декларация базы его покрывает. Кит намерение не угадывает — семь заходов
# гейта показали, что на любую эвристику (basename, манифест-сосед,
# курируемые каталоги, снапшот-каталоги) строится контрпример; декларация
# же сама проходит ревью через PR. `core.quotePath=false` даёт сырые пути,
# согласованные между diff --name-only и check-attr; кавыченные заголовки
# самого дифа — @id:review-kit-quoted-diff-headers.
git -c core.quotePath=false diff --name-only "$mb..$head_sha" \
    > "$work/changed-paths.txt"
# `--source` появился в git 2.38, и возможность ПРОБУЕТСЯ отдельно от
# боевого вызова: на старом git фильтр ДЕГРАДИРУЕТ до отсутствия —
# именованно, предупреждением в stderr, — а не убивает каждый непустой
# прогон кодом 2 (десятый заход гейта на #99: pre-push блокировал даже
# крошечный диф без единого generated-файла). Направление деградации — в
# сторону ревью: код никогда не прячется; худший исход — крупный
# объявленный диф упирается в явный отказ по потолку, где рецепт назван.
# Провал боевого вызова ПОСЛЕ успешной пробы — уже не совместимость, а
# настоящий отказ инструмента: код 2.
collect_declared() {
    # $1 — tree-ish, $2 — файл результата: объявленные пути дифа по
    # декларации этого дерева. `linguist-generated=true` даёт "true", голый
    # атрибут — "set"; оба — объявление. Парсинг с ХВОСТА строки: путь может
    # содержать ": ". `sort` — для `comm` ниже.
    if ! git -c core.quotePath=false check-attr --stdin \
        --source="$1" linguist-generated \
        < "$work/changed-paths.txt" > "$work/generated-attrs.txt"; then
        echo "не удалось прочитать linguist-generated из дерева $1" \
            "(git check-attr --source)." >&2
        exit 2
    fi
    sed -n -e 's/: linguist-generated: true$//p' \
        -e 's/: linguist-generated: set$//p' \
        "$work/generated-attrs.txt" | sort > "$2"
}

if git check-attr --source="$trusted_base" linguist-generated -- probe \
    >/dev/null 2>&1; then
    # Направления декларации АСИММЕТРИЧНЫ (девятый и одиннадцатый заходы
    # гейта на #99): добавление действует только ВЛИТЫМ — читается с
    # ВЕРХУШКИ доверенной базы (как BASE_SHA в CI), не из merge-base:
    # декларация, влитая в base после ответвления ветки, есть в merge-ref
    # дереве CI, но её нет ни в mb, ни в голом head — пересечение по ним
    # давало ложный отказ по потолку локально при зелёном CI (двенадцатый
    # заход). Снятие действует СРАЗУ: head ветирует пересечением, но только
    # когда PR вообще правит какой-нибудь `.gitattributes` — PR, не трогавший
    # деклараций, ничего не отзывал, и действует список базы один (так же
    # ведёт себя merge-ref дерево CI: `.gitattributes` базы в нём есть,
    # пока PR его не менял). Остаточный край: PR правит один
    # `.gitattributes`, а пост-форковая декларация живёт в другом — тогда
    # пересечение её уронит и файл останется в дифе: отказ в сторону ревью.
    #
    # "ПРАВИТ ЛИ PR `.gitattributes`" — вопрос про PR ЦЕЛИКОМ, то есть про
    # отрезок `trusted_mb..head`, а НЕ про суженный диапазон дифа. Пока базы
    # совпадали, это был один отрезок, и вето гейтилось по `changed-paths.txt`
    # (диапазон). Разведя базы, тот же гейт поменял бы направление отказа на
    # противоположное — в сторону СОКРЫТИЯ (находка терминального ревью этой
    # ветки, major/high): влитая база объявляет `dist/* linguist-generated`,
    # ветка первым коммитом переводит `dist/` в рукописный код и снимает
    # декларацию, круг 1 краснеет; адресный recheck зовётся ровно как велит
    # README (`--base <голова круга 1> --trusted-base origin/master`), и
    # `.gitattributes` в суженный диапазон уже не попадает — вето не
    # включается, снятая декларация продолжает действовать, и фикс-коммиты по
    # `dist/` вырезаются из дифа маркером. Модель не видит ни строки, кит
    # выходит нулём — тот же approve поверх request-changes, ради закрытия
    # которого флаг и заведён, только через другую дверь.
    #
    # Отдельный `git diff` только при разведённых базах: при умолчании
    # `$trusted_mb` == `$mb`, список тот же побайтно, и лишний вызов git был
    # бы платой всего флота за ветку, нужную обвязке адресного recheck.
    collect_declared "$trusted_base" "$work/generated-base.txt"
    if [ "$trusted_base_explicit" -eq 0 ]; then
        gitattr_probe="$work/changed-paths.txt"
    else
        gitattr_probe="$work/trusted-changed-paths.txt"
        if ! git -c core.quotePath=false diff --name-only \
            "$trusted_mb..$head_sha" > "$gitattr_probe"; then
            echo "не удалось перечислить пути отрезка" \
                "$trusted_mb..$head_sha (git diff --name-only) —" \
                "правит ли PR .gitattributes, установить нечем." >&2
            exit 2
        fi
    fi
    if grep -Eq '(^|/)\.gitattributes$' "$gitattr_probe"; then
        collect_declared "$head_sha" "$work/generated-head.txt"
        comm -12 "$work/generated-base.txt" "$work/generated-head.txt" \
            > "$work/generated-paths.txt"
    else
        cp "$work/generated-base.txt" "$work/generated-paths.txt"
    fi
else
    echo "предупреждение: git check-attr --source недоступен (git < 2.38) —" \
        "generated-фильтр выключен, объявленные файлы ревьюируются" \
        "построчно." >&2
    : > "$work/generated-paths.txt"
fi
set -- --prompt "$prompt" --diff "$work/diff.patch"
# ДЕТЕКЦИЯ, как в CI (восьмой заход): кит могли обновить наполовину — новый
# local.sh при старом build-prompt.sh (REVIEW_KIT_DIR / вендор-копия), и
# слепая передача нового флага убивала бы любой непустой прогон кодом 2
# (usage старого скрипта), а pre-push блокировал бы пуш (тринадцатый заход
# гейта на #99). Для раскатки кита по флоту перекос версий копий — штатный
# режим, не край. Флаг передаётся только когда механика кита его знает;
# иначе фильтр выключается именованно — в сторону ревью.
# Флаг передаётся без повторной феатур-детекции: непустой список может
# существовать только там, где фильтр отработал, а фильтр выше выключает
# сам себя, если сборщик флага не знает. Второй `grep` здесь создал бы
# ложную развилку «список есть, а объявить нечем» — состояние, которого по
# построению не бывает, и молчаливый выход из которой был бы тем самым
# дефектом steward#176.
[ ! -s "$work/withheld.list" ] || set -- "$@" --withheld-list "$work/withheld.list"
if grep -q -- '--generated-list' "$kit_dir/build-prompt.sh"; then
    set -- "$@" --generated-list "$work/generated-paths.txt"
else
    echo "предупреждение: build-prompt.sh кита не знает --generated-list" \
        "(кит обновлён наполовину) — generated-фильтр выключен, объявленные" \
        "файлы ревьюируются построчно." >&2
fi
[ "$use_context" -eq 1 ] && set -- "$@" --context "$work/context.txt"
# Потолки — та же версионная дисциплина, что --generated-list, но
# направление другое (пятнадцатый заход гейта на #99): потолок запрошен
# пользователем ЯВНО, и молча выбросить его нельзя (довод пустого значения
# в парсере) — несовместимость полуобновлённого кита называется отказом с
# причиной, а не тихой деградацией и не usage старого скрипта.
if [ -n "$max_diff_bytes" ] || [ -n "$max_diff_files" ]; then
    if grep -q -- '--max-diff-bytes' "$kit_dir/build-prompt.sh"; then
        if [ -n "$max_diff_bytes" ]; then
            set -- "$@" --max-diff-bytes "$max_diff_bytes"
        fi
        if [ -n "$max_diff_files" ]; then
            set -- "$@" --max-diff-files "$max_diff_files"
        fi
    else
        echo "build-prompt.sh кита не знает --max-diff-bytes/--max-diff-files" \
            "(кит обновлён наполовину) — явный оверрайд потолка выполнить" \
            "нельзя." >&2
        exit 2
    fi
fi
sh "$kit_dir/build-prompt.sh" "$@" > "$work/prompt.txt"

# --- отпечаток входа ревью (--fingerprint-only) -----------------------------
# Компоненты хешируются как framed byte streams: перед байтами каждой — имя и
# ТОЧНАЯ длина в байтах, поэтому склейка инъективна (байты компоненты не могут
# изобразить заголовок следующей — читатель знает, сколько читать). Версия
# протокола — первая строка потока: смена самой механики отпечатка (состав,
# framing) обязана инвалидировать все старые наследования, для этого достаточно
# поднять v1 → v2. Состав: итоговый prompt.txt (он уже несёт канонизированный
# диф, base-контекст и текст инструкций с детерминированными маркерами), точные
# байты схемы и порога, эффективное значение review_cmd (смена модели/effort —
# другой ревьюер, наследовать нельзя). Диф — вывод git diff: на одной машине
# детерминирован; расхождение версий/конфига git между машинами даст промах
# кэша — в сторону полного ревью, не в сторону ложного наследования.
if [ "$fp_only" -eq 1 ]; then
    threshold_script="$kit_dir/apply-threshold.sh"
    # `-f` вместе с `-r`: читаемый КАТАЛОГ проходит `-r`, а `cat` на нём падает
    # уже внутри сборки потока (находка гейта этой же ветки).
    if [ ! -f "$threshold_script" ] || [ ! -r "$threshold_script" ]; then
        echo "порог нечитаем или не файл: $threshold_script — порог есть" \
            "компонент отпечатка." >&2
        exit 2
    fi
    if command -v sha256sum >/dev/null 2>&1; then
        sha_cmd="sha256sum"
    elif command -v shasum >/dev/null 2>&1; then
        sha_cmd="shasum -a 256"
    else
        echo "нет ни sha256sum, ни shasum — отпечаток не построить." >&2
        exit 2
    fi
    fp_component() {
        # $1 — имя компоненты, $2 — файл с её точными байтами. Каждый шаг с
        # явным `|| return 1`: сбой чтения обязан провалить сборку потока, а
        # не выродиться в отпечаток от неполного входа.
        fp_len=$(wc -c < "$2" | tr -d ' 	') || return 1
        printf 'component %s length %s\n' "$1" "$fp_len" || return 1
        cat "$2" || return 1
    }
    assemble_fp_stream() {
        printf 'protocol codex-terminal-review-fingerprint-v1\n' &&
            fp_component prompt "$work/prompt.txt" &&
            fp_component schema "$schema" &&
            fp_component threshold "$threshold_script" &&
            fp_component review_cmd "$work/review-cmd.txt"
    }
    printf '%s' "$review_cmd" > "$work/review-cmd.txt"
    # Поток — через файл, не пайплайн: статус пайплайна в POSIX sh — статус
    # ПОСЛЕДНЕЙ команды, и упавший производитель молча маскировался бы хешем
    # обрезанного потока.
    if ! assemble_fp_stream > "$work/fp-stream.bin"; then
        echo "не удалось собрать поток отпечатка (компонент нечитаем)." >&2
        exit 2
    fi
    if ! fp_line=$($sha_cmd < "$work/fp-stream.bin"); then
        echo "хеширование отпечатка не удалось ($sha_cmd)." >&2
        exit 2
    fi
    # Дайджест валидируется, а не обрезается: хешер с кодом 0, но битым
    # выводом (сломанный shim в PATH) иначе печатал бы «отпечаток»,
    # нарушающий контракт 64-hex, — и будущий caller унёс бы его как
    # cache key (находка гейта этой же ветки).
    set -- $fp_line
    fp_digest="${1:-}"
    case "$fp_digest" in
        *[!0-9a-f]*) fp_digest="" ;;
    esac
    if [ "${#fp_digest}" -ne 64 ]; then
        echo "хешер вернул не 64-hex дайджест ($sha_cmd): '$fp_line'" >&2
        exit 2
    fi
    printf '%s\n' "$fp_digest"
    exit 0
fi

# Промпт идёт на stdin, а не аргументом: диф — недоверенный текст, и в argv он
# не попадает ни здесь, ни в CI. Ревьюер в песочнице read-only: он читает, а не
# правит рабочее дерево.
#
# $review_cmd НАМЕРЕННО без кавычек (ветка без reviewer_exec, ниже): REVIEW_CMD
# — команда целиком (может нести свои флаги, например 'codex exec --model X'),
# и должна разбиться на отдельные argv-слова через word splitting, а не уйти
# одним литералом в argv[0], где `exec`/бинарь с пробелом внутри имени не
# существует (ENOENT).
#
# Ревьюер запускается БЕЗ правки PATH (находка терминального ревью на этой
# ветке): префикс `PATH="$kit_dir:$PATH"` ставил каталог кита первым и для
# codex-умолчания, и посторонний файл scripts/review/codex у потребителя —
# не член PIN, checksum лишние файлы игнорирует по контракту — подменил бы
# ревьюера при зелёном copy-integrity. Адаптер зовётся по абсолютному пути;
# в review_cmd (отпечаток, --print-review-cmd) остаётся голое имя — строка
# машинно-независима и называет тот же файл кита.
run_reviewer() {
    if [ -n "$reviewer_exec" ]; then
        # review_cmd = "harness-claude --model X": голое имя заменяется путём,
        # его флаги (после первого пробела) идут перед аргументами вызова.
        set -- ${review_cmd#* } "$@"
        "$reviewer_exec" "$@"
    else
        $review_cmd "$@"
    fi
}
if ! run_reviewer --sandbox read-only \
        --output-schema "$schema" \
        --output-last-message "$work/verdict.json" \
        - < "$work/prompt.txt" >/dev/null 2>"$work/reviewer.err"; then
    echo "ревьюер не отработал:" >&2
    cat "$work/reviewer.err" >&2
    exit 3
fi

if [ ! -s "$work/verdict.json" ]; then
    echo "ревьюер завершился успешно, но вердикта не оставил" >&2
    exit 3
fi

# Копия вердикта ДО порога (спека review-eval §7, D4): eval обязан видеть
# находки и при коде 1, и при отказе валидации порога. Атомарно: tmp в
# каталоге цели + mv; потерять запрошенный артефакт молча нельзя — код 2.
if [ -n "${REVIEW_VERDICT_OUT:-}" ]; then
    verdict_out_dir=$(dirname "$REVIEW_VERDICT_OUT")
    mkdir -p "$verdict_out_dir" || { echo "REVIEW_VERDICT_OUT: не создать каталог $verdict_out_dir" >&2; exit 2; }
    verdict_tmp=$(mktemp "$verdict_out_dir/.verdict.XXXXXX") \
        || { echo "REVIEW_VERDICT_OUT: не создать временный файл в $verdict_out_dir" >&2; exit 2; }
    # Trap уже зарегистрирован (см. work=$(mktemp -d) выше) и читает
    # verdict_tmp по имени при срабатывании — присваивание здесь достаточно,
    # повторная регистрация не нужна и не переживает апостроф в пути.
    if ! cp "$work/verdict.json" "$verdict_tmp" || ! mv "$verdict_tmp" "$REVIEW_VERDICT_OUT"; then
        rm -f "$verdict_tmp"
        echo "REVIEW_VERDICT_OUT: не удалось сохранить вердикт в $REVIEW_VERDICT_OUT" >&2
        exit 2
    fi
    if [ ! -f "$REVIEW_VERDICT_OUT" ]; then
        # Пройденный по значению `-d` guard выше отсекает REVIEW_VERDICT_OUT,
        # который УЖЕ каталог — но не пересекающиеся sidecar-пути (находка
        # терминального ревью этой ветки): REVIEW_USAGE_OUT ВНУТРИ дерева
        # REVIEW_VERDICT_OUT (`REVIEW_VERDICT_OUT=/x/artifact`,
        # `REVIEW_USAGE_OUT=/x/artifact/usage.json`) заставляет адаптер
        # сделать `mkdir -p /x/artifact` уже ПОСЛЕ раннего guard'а local.sh —
        # и `mv` выше "успевает" структурно (POSIX-семантика: цель — каталог,
        # файл переносится ВНУТРЬ него, а не переименовывается в него),
        # оставляя осиротевший `.verdict.*` внутри. Зеркало post-mv проверки
        # адаптера (`[ -f "$verdict" ]`): убрать осиротевший файл и отказать
        # явно, а не молчать кодом 0 без вердикта по заявленному пути.
        rm -f "$REVIEW_VERDICT_OUT/$(basename "$verdict_tmp")"
        echo "REVIEW_VERDICT_OUT: вердикт не сохранён как файл по заданному" \
            "пути: $REVIEW_VERDICT_OUT" >&2
        exit 2
    fi
fi

sh "$kit_dir/apply-threshold.sh" --verdict "$work/verdict.json" --format "$format"
